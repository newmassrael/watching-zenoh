/// Upstream's payload-size histogram bounds, in bytes
/// (`commons/zenoh-stats/src/histogram.rs` @ `pub const PAYLOAD_SIZE_BUCKETS`).
/// A final `+Inf` bucket follows them.
pub const PAYLOAD_SIZE_BUCKETS: [u64; 7] = [0, 1 << 5, 1 << 10, 1 << 15, 1 << 20, 1 << 25, 1 << 30];

/// The number of buckets a payload histogram carries: the bounds plus `+Inf`.
const BUCKET_COUNT: usize = PAYLOAD_SIZE_BUCKETS.len() + 1;

/// How long a disconnected transport keeps its own partition before its
/// counters are folded into the retired bucket
/// (`commons/zenoh-stats/src/family.rs` @ `const GARBAGE_COLLECTION_DELAY`).
pub const GARBAGE_COLLECTION_DELAY_MS: u64 = 60_000;

/// Which way a counted message travelled.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum StatsDirection {
    /// Sent by this node.
    Tx,
    /// Received by this node.
    Rx,
}

impl StatsDirection {
    /// Both directions, in the order upstream registers their families.
    pub const ALL: [StatsDirection; 2] = [StatsDirection::Tx, StatsDirection::Rx];

    /// The family-name prefix (`tx` / `rx`).
    pub const fn label(self) -> &'static str {
        match self {
            StatsDirection::Tx => "tx",
            StatsDirection::Rx => "rx",
        }
    }

    /// The verb upstream's help strings use for this direction.
    const fn action(self) -> &'static str {
        match self {
            StatsDirection::Tx => "sent",
            StatsDirection::Rx => "received",
        }
    }

    const fn index(self) -> usize {
        self as usize
    }
}

