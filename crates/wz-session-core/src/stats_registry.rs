/// Who is on the other end of a transport — the per-transport partition key
/// (`commons/zenoh-stats/src/labels.rs` @ `pub(crate) struct TransportLabels`).
///
/// A unicast transport names its peer; a multicast transport names its group
/// and no peer; a peer seen on a multicast group names both. Every field is
/// written in every sample, an absent one as the empty string, which is what
/// `prometheus-client` does with a `None` label value.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TransportLabels {
    /// The peer's zid in zenoh's hex form.
    pub remote_zid: Option<String>,
    /// The peer's role.
    pub remote_whatami: Option<WhatAmI>,
    /// The multicast group locator.
    pub remote_group: Option<String>,
    /// The peer certificate's common name.
    pub remote_cn: Option<String>,
}

impl TransportLabels {
    /// A unicast transport to `zid`.
    pub fn unicast(zid: &str, whatami: WhatAmI, cn: Option<&str>) -> Self {
        TransportLabels {
            remote_zid: Some(String::from(zid)),
            remote_whatami: Some(whatami),
            remote_group: None,
            remote_cn: cn.map(String::from),
        }
    }

    /// A multicast transport on `group`.
    pub fn multicast(group: &str) -> Self {
        TransportLabels {
            remote_zid: None,
            remote_whatami: None,
            remote_group: Some(String::from(group)),
            remote_cn: None,
        }
    }

    /// A peer `zid` seen on the multicast `group`.
    pub fn multicast_peer(zid: &str, whatami: WhatAmI, group: &str) -> Self {
        TransportLabels {
            remote_zid: Some(String::from(zid)),
            remote_whatami: Some(whatami),
            remote_group: Some(String::from(group)),
            remote_cn: None,
        }
    }

    /// Whether closing one of this transport's links changes the
    /// `zenoh_links_opened` gauge. Upstream decrements it only for a transport
    /// that is not a multicast PEER entry
    /// (`commons/zenoh-stats/src/registry.rs` @ `if transport.remote_group.is_none() || transport.remote_zid.is_none() {`),
    /// because a peer entry's link was never counted as a new link.
    fn owns_its_links(&self) -> bool {
        self.remote_group.is_none() || self.remote_zid.is_none()
    }

    fn write(&self, w: &mut LabelWriter<'_>) {
        w.opt("remote_zid", self.remote_zid.as_deref());
        w.opt("remote_whatami", self.remote_whatami.map(WhatAmI::to_str));
        w.opt("remote_group", self.remote_group.as_deref());
        w.opt("remote_cn", self.remote_cn.as_deref());
    }
}

/// One link of a transport — the per-link partition key.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct LinkLabels {
    /// This node's end, as a locator string.
    pub src_locator: String,
    /// The remote end, as a locator string.
    pub dst_locator: String,
}

impl LinkLabels {
    /// A link from `src` to `dst`.
    pub fn new(src: &str, dst: &str) -> Self {
        LinkLabels {
            src_locator: String::from(src),
            dst_locator: String::from(dst),
        }
    }

    /// The `protocol` label this link's samples carry: the remote locator's
    /// scheme when upstream knows it, and otherwise the WHOLE remote locator
    /// (`commons/zenoh-stats/src/labels.rs` @ `static KNOWN_PROTOCOLS`) — so an
    /// unknown scheme gets one series per remote end, which is upstream's.
    pub fn protocol(&self) -> String {
        const KNOWN_PROTOCOLS: [&str; 9] = [
            "tcp",
            "udp",
            "tls",
            "quic",
            "unixsock-stream",
            "ws",
            "serial",
            "unixpipe",
            "vsock",
        ];
        let scheme = self
            .dst_locator
            .split_once('/')
            .map_or(self.dst_locator.as_str(), |(scheme, _)| scheme);
        match KNOWN_PROTOCOLS.iter().find(|known| **known == scheme) {
            Some(known) => String::from(*known),
            None => self.dst_locator.clone(),
        }
    }

    fn write(&self, w: &mut LabelWriter<'_>) {
        w.label("src_locator", &self.src_locator);
        w.label("dst_locator", &self.dst_locator);
    }
}

