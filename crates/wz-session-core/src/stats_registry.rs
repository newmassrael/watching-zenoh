//! R2821 — the pin's stats REGISTRY: the node-wide collection model and the
//! OpenMetrics document it encodes, which is what a zenoh node built with
//! `stats` answers on `@/<zid>/<whatami>/metrics`.
//!
//! # Why this module exists — the body wz served was a different document
//!
//! At zenoh 1.10 the metrics leg under `stats` does not render per-session
//! counters at all. It encodes one runtime-wide registry
//! (`zenoh/src/net/runtime/adminspace.rs` @ `.encode_metrics(`), built in
//! `commons/zenoh-stats/src/registry.rs` @ `pub fn encode_metrics(`, whose
//! families are keyed by a LABEL SET and partitioned by TRANSPORT and LINK:
//! `zenoh_tx_bytes_total{local_id,local_whatami,protocol}`, a
//! `…_per_transport_…` twin carrying `remote_zid` / `remote_whatami` /
//! `remote_group` / `remote_cn` / `disconnected`, a `…_per_link_…` twin
//! carrying `src_locator` / `dst_locator`, payload HISTOGRAMS, and a per-key
//! histogram family. The block wz appended until this round
//! (`tx_bytes 140`, `tx_n_msgs{medium="net"}`) was the 1.5.0-era JSON field
//! names rendered as OpenMetrics — a document no pinned zenoh node emits.
//!
//! That one structural gap is the BASE under three residuals the
//! `adminspace-metrics` atom carried separately: the four query parameters
//! upstream honours (`per_transport` / `per_link` / `disconnected` /
//! `per_key`) had nothing to select, a mesh host had no counterpart to the
//! runtime-wide aggregate, and the per-transport partitions did not exist. All
//! three are partitions OF this registry, so they are built here once rather
//! than patched onto the flat body three times.
//!
//! # What is mirrored, and how it was measured
//!
//! Everything below is read from the pin and then CHECKED AGAINST IT: the test
//! module compares this encoder's output with documents the real `zenoh-stats`
//! crate (1.10.1, `prometheus-client` 0.24.1) produced for the same event
//! sequences, kept in `stats_registry/zenoh_1_10_1.golden` and regenerated by
//! `scripts/lib/zenoh_stats_golden.py`. The comparison is per descriptor block:
//! the descriptor sequence must match exactly and each block's sample lines must
//! match as a multiset, because upstream iterates `HashMap`s and its line order
//! within a block is not a property of the format.
//!
//! The collection rules that are easy to get wrong, each taken from
//! `commons/zenoh-stats/src/family.rs` @ `fn collect(&self)`:
//!
//! - the aggregate STARTS from the retired bucket (transports garbage-collected
//!   after their disconnection), which carries no transport labels;
//! - a transport that is disconnected but not yet collected is SKIPPED from the
//!   aggregate as well as from the per-transport block unless the query asks for
//!   `disconnected=true` — so a counter can fall when a peer leaves and rise
//!   again a minute later, which is upstream's behaviour and is kept;
//! - a per-link block is written only when some transport holds a link-scoped
//!   cell, while the per-transport descriptor is written whenever it is asked
//!   for, samples or not.
//!
//! # Deliberate divergences
//!
//! - Label values are ESCAPED (`\`, `"`, newline) where `prometheus-client`
//!   writes them raw. No value this registry is given contains those bytes in
//!   practice, so the output is identical; the escape only keeps a pathological
//!   locator or version from producing an invalid document. The build-info
//!   block has made the same choice since R2414.
//! - Histogram sums are kept as integers and converted to a float when written,
//!   where upstream converts each transport's sum before adding. The two agree
//!   while the total stays below 2^53 bytes; past that the last digit may differ.
//! - The ORDER of samples inside a block is deterministic here (label order,
//!   then registration order), where upstream's is hash order.

