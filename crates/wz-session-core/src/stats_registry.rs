/// Why a message was dropped
/// (`commons/zenoh-stats/src/labels.rs` @ `pub enum ReasonLabel`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ReasonLabel {
    /// Refused by an access-control rule.
    AccessControl,
    /// Refused by a full priority queue under `Drop` congestion control.
    Congestion,
    /// Refused by a downsampling interceptor.
    Downsampling,
    /// Refused by a low-pass filter.
    LowPass,
    /// No link could carry it.
    NoLink,
}

impl ReasonLabel {
    /// Upstream's label value.
    pub const fn label(self) -> &'static str {
        match self {
            ReasonLabel::AccessControl => "access-control",
            ReasonLabel::Congestion => "congestion",
            ReasonLabel::Downsampling => "downsampling",
            ReasonLabel::LowPass => "low-pass",
            ReasonLabel::NoLink => "no-link",
        }
    }
}

