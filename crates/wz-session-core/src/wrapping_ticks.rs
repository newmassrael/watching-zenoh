//! Whether a span of ticks has passed, over a counter that wraps at 2^32.
//!
//! A deadline and a sampling period are the same question: have `timeout` ticks passed since
//! `last`? The supervisor asks it of a checkpoint and the resource sampler of its period
//! (`docs/observation-plane.md` M3 and M4), so it is written once, here.
//!
//! The difference of two readings is taken modulo 2^32, so a wrap of the counter between the two
//! readings is the ordinary case and not a special one. That comparison cannot tell a span of
//! `timeout` ticks from one of `timeout + 2^32`, so a timeout is at most [`MAX_TIMEOUT_TICKS`], half
//! the range: past that, a counter that went round looks like one that did not move, and the check
//! must be made at least once in every `2^32 - timeout` ticks to see a span at all.

/// The longest timeout a comparison can have: the difference of two readings is compared modulo
/// 2^32, so a timeout past half the range cannot be told from a counter that went round.
pub const MAX_TIMEOUT_TICKS: u32 = i32::MAX as u32;

// The two functions are SCE `algorithm` documents (`sources/algorithms/tick_elapsed.scxml` and
// `tick_until_due.scxml`), committed at `out/wz-session-core/`, `include!`-ed from there
// (regenerated by `scripts/regen-codegen.sh`). The arithmetic they state, the wrapping and the
// saturating subtraction, is the generator's, so it is not written a second time by hand here.
mod generated {
    include!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../out/wz-session-core",
        "/tick_elapsed.rs"
    ));
    include!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../out/wz-session-core",
        "/tick_until_due.rs"
    ));
}

/// Whether `timeout` ticks have passed from `last` to `now`, both readings of a counter that
/// wraps at 2^32.
pub use generated::tick_elapsed as elapsed;

/// How many of `period` ticks remain from `last` to `now`, both readings of a counter that wraps
/// at 2^32: the period less the ticks that passed, and 0 once the period is over.
pub use generated::tick_until_due as until_due;

#[cfg(test)]
mod tests {
    use super::*;

    /// The arithmetic the two documents state, written as the plain functions of the standard
    /// library: the generated bodies are held to it over the edges of the range, so a generator
    /// that changed what a wrapping or a saturating subtraction means would be seen here.
    #[test]
    fn the_generated_functions_are_the_arithmetic_their_documents_name() {
        let edges = [
            0,
            1,
            2,
            999,
            1000,
            1001,
            0x7FFF_FFFF,
            0x8000_0000,
            0xFFFF_FFFE,
            u32::MAX,
        ];
        for now in edges {
            for last in edges {
                for span in edges {
                    let passed = now.wrapping_sub(last);
                    assert_eq!(
                        elapsed(now, last, span),
                        passed >= span,
                        "{now} {last} {span}"
                    );
                    assert_eq!(
                        until_due(now, last, span),
                        span.saturating_sub(passed),
                        "{now} {last} {span}"
                    );
                }
            }
        }
    }

    #[test]
    fn an_overdue_period_has_nothing_left_and_does_not_wrap_to_a_huge_wait() {
        assert_eq!(until_due(5000, 100, 1000), 0);
        assert_eq!(until_due(1100, 100, 1000), 0);
        assert_eq!(until_due(1099, 100, 1000), 1);
        // Across a wrap of the counter: 600 of 1000 passed between 2^32 - 200 and 400.
        assert_eq!(until_due(400, u32::MAX - 199, 1000), 400);
    }

    #[test]
    fn a_span_is_a_difference_taken_modulo_the_counter() {
        assert!(!elapsed(100, 100, 5));
        assert!(!elapsed(104, 100, 5));
        assert!(elapsed(105, 100, 5));
        // The counter went round between the two readings: 10 ticks passed.
        assert!(elapsed(5, u32::MAX - 4, 10));
        assert!(!elapsed(4, u32::MAX - 4, 10));
    }

    #[test]
    fn the_longest_timeout_is_half_the_range() {
        assert_eq!(MAX_TIMEOUT_TICKS, 2_147_483_647);
        assert!(elapsed(MAX_TIMEOUT_TICKS, 0, MAX_TIMEOUT_TICKS));
        assert!(!elapsed(MAX_TIMEOUT_TICKS - 1, 0, MAX_TIMEOUT_TICKS));
    }
}
