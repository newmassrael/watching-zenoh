    /// A text split on `/` into a fixed array, the form the reference takes: `None` when a chunk
    /// is empty, or when the key is deeper than the reference is asked about (or than the fixed
    /// backing holds).
    fn split_for_reference(text: &str) -> Option<([&str; 40], usize)> {
        let mut chunks = [""; 40];
        let mut len = 0;
        for chunk in text.split('/') {
            if chunk.is_empty() || len == chunks.len() {
                return None;
            }
            chunks[len] = chunk;
            len += 1;
        }
        if crate::bounded::ENFORCES_CAPACITY && len > MAX_KEYEXPR_CHUNKS {
            return None;
        }
        Some((chunks, len))
    }

    /// The text relation answers what the reference answers for every pair of a corpus that
    /// holds both kinds of key (with and without a wildcard), the malformed ones (an empty
    /// chunk, a leading or trailing `/`, the empty key), keys that differ only by a prefix, a
    /// suffix or one chunk, and two keys one chunk deeper than the fixed backing holds.
    #[test]
    fn intersects_agrees_with_the_reference_over_a_corpus() {
        let corpus = [
            "",
            "a",
            "a/b",
            "a/b/",
            "/a/b",
            "a//b",
            "a/b/c",
            "ab/c",
            "a/bc",
            "a/b/c/d",
            "@/5a1c0ffee001/peer/status/connect",
            "@/5a1c0ffee001/peer/status/config",
            "@/5a1c0ffee001/peer/status",
            "@/5a1c0ffee001/peer/status/connect/x",
            "a/*",
            "*/b",
            "a/**",
            "**",
            "a/b$*",
            "$*",
            "a/$b",
            "a/b$",
            "a/*/c",
            "@/5a1c0ffee001/**",
        ];
        let deep_a = "a/".repeat(MAX_KEYEXPR_CHUNKS) + "a";
        let deep_b = "a/".repeat(MAX_KEYEXPR_CHUNKS) + "b";
        let keys = corpus
            .iter()
            .copied()
            .chain([deep_a.as_str(), deep_b.as_str()]);
        for candidate in keys.clone() {
            for target in keys.clone() {
                let want = match (split_for_reference(candidate), split_for_reference(target)) {
                    (Some((a, a_len)), Some((b, b_len))) => {
                        reference::intersect_by_descent(&a[..a_len], &b[..b_len])
                    }
                    _ => false,
                };
                assert_eq!(
                    keyexpr_intersects(candidate, target),
                    want,
                    "candidate {candidate:?} against target {target:?}"
                );
                assert_eq!(keyexpr_intersects_text(candidate, target), want);
            }
        }
    }

    /// The chunks every kind of arm reads: two literals, `*`, `**`, a verbatim chunk, `$*` at
    /// either end of a chunk and in its middle, and a lone `$*`.
    const TABLE_ALPHABET: [&str; 9] = ["a", "b", "*", "**", "@v", "a$*", "$*b", "a$*b", "$*"];

    /// The `index`-th sequence of one to three chunks of [`TABLE_ALPHABET`], held in a fixed array.
    fn table_sequence(mut index: usize) -> ([&'static str; 3], usize) {
        let mut chunks = [""; 3];
        let mut len = 1;
        let mut count = TABLE_ALPHABET.len();
        while index >= count && len < 3 {
            index -= count;
            len += 1;
            count *= TABLE_ALPHABET.len();
        }
        for slot in chunks[..len].iter_mut() {
            *slot = TABLE_ALPHABET[index % TABLE_ALPHABET.len()];
            index /= TABLE_ALPHABET.len();
        }
        (chunks, len)
    }

    /// The `/`-joined text of a table sequence, in a fixed buffer.
    fn joined(chunks: &[&str]) -> crate::bounded::BoundedString<32> {
        let mut text = crate::bounded::BoundedString::new();
        for (index, chunk) in chunks.iter().enumerate() {
            if index > 0 {
                text.push_str("/").expect("the buffer holds three chunks");
            }
            text.push_str(chunk).expect("the buffer holds three chunks");
        }
        text
    }

    /// The generated relations answer what the hand-written ones answered, for every pair of
    /// sequences of one to three chunks over every kind of chunk: 819 x 819 pairs for each of the
    /// three relations. Two `**` on a side reach the dynamic programme's every arm.
    #[test]
    fn the_generated_relations_answer_what_the_hand_written_ones_answered() {
        let n = TABLE_ALPHABET.len();
        let sequences = n + n * n + n * n * n;
        assert_eq!(
            table_sequence(sequences - 1).1,
            3,
            "the count reaches three"
        );
        for x in 0..sequences {
            let (a, a_len) = table_sequence(x);
            let a = &a[..a_len];
            let a_text = joined(a);
            for y in 0..sequences {
                let (b, b_len) = table_sequence(y);
                let b = &b[..b_len];
                let b_text = joined(b);
                assert_eq!(
                    keyexpr_intersects(&a_text, &b_text),
                    reference::intersect_by_descent(a, b),
                    "intersects {a:?} {b:?}"
                );
                #[cfg(feature = "keyexpr-includes")]
                assert_eq!(
                    keyexpr_includes(&a_text, &b_text),
                    reference::includes_by_descent(a, b),
                    "includes {a:?} {b:?}"
                );
                assert_eq!(
                    keyexpr_matches(&a_text, &b_text),
                    reference::matches_by_walk(a, b),
                    "matches {a:?} {b:?}"
                );
            }
        }
    }

    /// Two patterns of fifteen `**/x` pairs and a last chunk, as deep as the fixed backing holds,
    /// that end in different chunks share no key: a descent without memory tried each `**` both
    /// ways, about 2^30 paths (the nightly fuzzer's `text` target found a pair of this shape
    /// taking over ten seconds). The programme fills 32 x 32 cells. A regression shows as this
    /// test not finishing.
    #[test]
    fn many_double_stars_on_both_sides_are_answered_in_polynomial_time() {
        const PAIRS: usize = (MAX_KEYEXPR_CHUNKS - 1) / 2;
        let a_head = "**/x/".repeat(PAIRS);
        let a = a_head.clone() + "y";
        let mut b = a_head + "z";
        assert!(!keyexpr_intersects(&a, &b));
        #[cfg(feature = "keyexpr-includes")]
        assert!(!keyexpr_includes(&a, &b));
        b = a.clone();
        assert!(keyexpr_intersects(&a, &b) || !cfg!(feature = "keyexpr-wildcard-double"));
        #[cfg(feature = "keyexpr-includes")]
        assert!(keyexpr_includes(&a, &b));
    }

    /// Two keys of more than 63 chunks that both hold `**` are refused: the bound of the
    /// programme's `uint64` row. One of at most 63 chunks against a deeper one is answered.
    #[cfg(all(
        feature = "alloc",
        not(feature = "bounded-heapless"),
        feature = "keyexpr-wildcard-double"
    ))]
    #[test]
    fn the_programme_answers_while_one_side_has_at_most_63_chunks() {
        let deep = "a/".repeat(70) + "**";
        assert!(keyexpr_intersects("a/**", &deep));
        assert!(keyexpr_intersects(&deep, "a/**"));
        assert!(keyexpr_intersects(&("a/".repeat(62) + "**"), &deep));
        assert!(!keyexpr_intersects(&deep, &deep.replace("a/a/", "a/b/")));
    }

    /// The inclusion programme with its bits over the covering side: a covered key of more than
    /// 63 chunks against a covering one of at most 63, both holding `**`, puts the covered key on
    /// the rows, where its `**` does not stretch and the covering one's does. Each answer is the
    /// reference descent's, and two such keys of more than 63 chunks each are refused.
    #[cfg(all(
        feature = "alloc",
        not(feature = "bounded-heapless"),
        feature = "keyexpr-wildcard-double",
        feature = "keyexpr-includes"
    ))]
    #[test]
    fn inclusion_answers_with_its_bits_over_the_covering_side() {
        fn chunks<'a>(text: &'a str, out: &mut [&'a str; 80]) -> usize {
            let mut len = 0;
            for (index, chunk) in text.split('/').enumerate() {
                out[index] = chunk;
                len = index + 1;
            }
            len
        }
        let deep = "a/".repeat(70) + "**";
        let deep_verbatim = "a/".repeat(70) + "**/@v";
        let shallow = "a/".repeat(62) + "**";
        let cases = [
            ("a/**", deep.as_str(), true),
            ("b/**", deep.as_str(), false),
            (shallow.as_str(), deep.as_str(), true),
            ("a/**/@v", deep_verbatim.as_str(), true),
            ("a/**", deep_verbatim.as_str(), false),
            (deep.as_str(), "a/**", false),
        ];
        for (superset, subset, want) in cases {
            assert_eq!(
                keyexpr_includes(superset, subset),
                want,
                "{superset:?} includes {subset:?}"
            );
            let (mut sup, mut sub) = ([""; 80], [""; 80]);
            let (sup_len, sub_len) = (chunks(superset, &mut sup), chunks(subset, &mut sub));
            assert_eq!(
                reference::includes_by_descent(&sup[..sup_len], &sub[..sub_len]),
                want,
                "the reference on {superset:?} and {subset:?}"
            );
        }
        assert!(!keyexpr_includes(&deep, &deep));
    }

