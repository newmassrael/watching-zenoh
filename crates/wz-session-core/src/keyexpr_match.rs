//! The keyexpr wildcard matcher: whether two key expressions share a key ([`keyexpr_intersects`]),
//! whether one covers every key of another (`keyexpr_includes`), and whether a pattern matches a
//! key read as a literal ([`keyexpr_matches`]). Every subscriber, queryable, liveliness, routing,
//! ACL and interceptor scan in wz asks one of these three.
//!
//! ## The matcher is SCE documents
//!
//! The three relations and the chunk steps they share are SCE `algorithm` documents
//! (`sources/algorithms/keyexpr_*.scxml`), generated into `out/wz-session-core/` and included here
//! (regenerated by `scripts/regen-codegen.sh`), so the Rust, C11 and C++ that read them are one
//! definition. They read the two key TEXTS directly: no split into chunks, no buffer of chunk
//! views, no allocation. Each key's shape (its chunk count, whether it holds `*` and `**`) is
//! read in one pass first; two keys without a `*` are compared as text. With `**` on one side at
//! most, the relation is a greedy walk with one backtrack frame (`keyexpr_walk.scxml`), which is
//! exact when only one side can take several chunks. With `**` on both sides it is a dynamic
//! programme over the two keys' prefixes whose rows are `uint64` bit sets, two of them at a time
//! (`keyexpr_relation_dp.scxml`, one programme for both relations: which side's `**` stretches
//! and which chunk step relates two chunks are its arguments); the side the bits stand for has
//! at most 63 chunks, and two such keys of more than 63 chunks each are refused. Until 2026-11-19
//! this module held the matcher by hand, a descent that remembered the suffix pairs it had
//! refuted, over keys split into a chunk view.
//!
//! ## What every relation refuses
//!
//! A text with an empty chunk (the empty text, a leading or trailing `/`, `//`) shares, covers and
//! matches nothing: it is not a key (zenoh's data route refuses such a key too). On the fixed
//! backing (`alloc` off, or `bounded-heapless`) a key of more than [`MAX_KEYEXPR_CHUNKS`] chunks
//! is refused as well, the bound every MCU table of keys is declared with.
//!
//! ## Per-capability switches (R311jf)
//!
//! The keyexpr wildcard and DSL capabilities are atomic catalog features (`§5.6`). Three are
//! composition toggles, handed to the generated matcher as its `wild_*` arguments:
//!
//! * `keyexpr-wildcard-single`: the whole-chunk `*`.
//! * `keyexpr-wildcard-double`: the multi-chunk `**`.
//! * `keyexpr-dollar-star`: the intra-chunk `$*` substring DSL.
//!
//! When a toggle is off its token **is a literal chunk** (a pattern `home/**` matches only the
//! literal key `home/**`): the same compile-flag elision zenoh-pico makes. The arguments are
//! constants of the build, so the compiler folds the branches of an absent wildcard away.
//! `keyexpr-includes` gates `keyexpr_includes`, the directional relation the ACL and routing
//! coverage scans ask. It is named here as code and not linked: a link from these docs would not
//! resolve in a build without the feature, which is a build these docs are also read in.
//!
//! ## @verbatim (R311y543)
//!
//! A chunk that begins with `@` is VERBATIM (zenoh's `has_direct_verbatim`): it belongs to the
//! admin namespace and is reached only by a byte-equal chunk, never by `*`, `**` or a `$*` chunk,
//! and `**` does not cross one. The rule was re-opened by a measurement: upstream's
//! `z_advanced_sub.c` on `demo/capic/**` against a real zenoh-pico advanced publisher received 7
//! samples of zenoh's own `@adv/pub/<zid>/<eid>/_` beacon traffic beside its 4 data samples, where
//! the real `libzenohc.so` on the identical wire received none of the 7. The rule is a chunk
//! class, not a wildcard behaviour, so it holds whatever the toggles are.

/// The most chunks a key of the fixed backing (`alloc` off, or `bounded-heapless`) has: a deeper
/// key is refused by every relation there, the bound of every MCU table of keys. On the growable
/// backing it bounds nothing here; other modules size their own views of a key by it.
pub const MAX_KEYEXPR_CHUNKS: usize = 32;

/// The build's wildcard switches, the `wild_*` arguments of the generated matcher.
const WILD_SINGLE: bool = cfg!(feature = "keyexpr-wildcard-single");
const WILD_DOUBLE: bool = cfg!(feature = "keyexpr-wildcard-double");
const WILD_DSL: bool = cfg!(feature = "keyexpr-dollar-star");

/// [`MAX_KEYEXPR_CHUNKS`] as the `uint32` the generated documents take.
const CHUNK_BOUND: u32 = {
    assert!(MAX_KEYEXPR_CHUNKS <= u32::MAX as usize);
    MAX_KEYEXPR_CHUNKS as u32
};

