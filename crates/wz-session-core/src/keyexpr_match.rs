    /// The matcher this module held by hand until 2026-11-19, kept as the reference the generated
    /// documents are held to: the chunk relations, the descent over chunk sequences without the
    /// memory of refuted pairs (exponential in the number of `**`, so it is asked only of short
    /// sequences), and the glob walk of a pattern over a literal key.
    mod reference {
        pub(super) const fn is_verbatim_chunk(chunk: &str) -> bool {
            matches!(chunk.as_bytes(), [b'@', ..])
        }

        #[cfg(feature = "keyexpr-dollar-star")]
        pub(super) fn chunk_matches_with_dsl(pattern: &str, target: &str) -> bool {
            let mut parts = pattern.split("$*").peekable();
            let mut remaining = target;
            let leading = parts.next().unwrap_or("");
            if !leading.is_empty() {
                match remaining.strip_prefix(leading) {
                    Some(rest) => remaining = rest,
                    None => return false,
                }
            }
            loop {
                let Some(part) = parts.next() else {
                    return false;
                };
                if parts.peek().is_none() {
                    return part.is_empty() || remaining.ends_with(part);
                }
                if part.is_empty() {
                    continue;
                }
                match remaining.find(part) {
                    Some(pos) => remaining = &remaining[pos + part.len()..],
                    None => return false,
                }
            }
        }

        pub(super) fn chunk_matches(pattern: &str, target: &str) -> bool {
            if pattern == target {
                return true;
            }
            if is_verbatim_chunk(pattern) || is_verbatim_chunk(target) {
                return false;
            }
            #[cfg(feature = "keyexpr-dollar-star")]
            if pattern.contains("$*") {
                return chunk_matches_with_dsl(pattern, target);
            }
            false
        }

        pub(super) fn chunk_intersects(a: &str, b: &str) -> bool {
            if a == b {
                return true;
            }
            if is_verbatim_chunk(a) || is_verbatim_chunk(b) {
                return false;
            }
            #[cfg(feature = "keyexpr-wildcard-single")]
            if a == "*" || b == "*" {
                return true;
            }
            #[cfg(feature = "keyexpr-dollar-star")]
            {
                let a_has_dsl = a.contains("$*");
                let b_has_dsl = b.contains("$*");
                if a_has_dsl || b_has_dsl {
                    return match (a_has_dsl, b_has_dsl) {
                        (true, false) => chunk_matches_with_dsl(a, b),
                        (false, true) => chunk_matches_with_dsl(b, a),
                        _ => {
                            let a_lead = a.split("$*").next().unwrap_or("");
                            let a_trail = a.rsplit("$*").next().unwrap_or("");
                            let b_lead = b.split("$*").next().unwrap_or("");
                            let b_trail = b.rsplit("$*").next().unwrap_or("");
                            (a_lead.starts_with(b_lead) || b_lead.starts_with(a_lead))
                                && (a_trail.ends_with(b_trail) || b_trail.ends_with(a_trail))
                        }
                    };
                }
            }
            false
        }

        #[cfg(feature = "keyexpr-includes")]
        pub(super) fn chunk_includes(a: &str, b: &str) -> bool {
            if a == b {
                return true;
            }
            if is_verbatim_chunk(a) || is_verbatim_chunk(b) {
                return false;
            }
            #[cfg(feature = "keyexpr-wildcard-single")]
            {
                if a == "*" {
                    return true;
                }
                if b == "*" {
                    return false;
                }
            }
            #[cfg(feature = "keyexpr-dollar-star")]
            if a.contains("$*") {
                return chunk_matches_with_dsl(a, b);
            }
            false
        }

        pub(super) fn intersect_by_descent(a: &[&str], b: &[&str]) -> bool {
            match (a.first(), b.first()) {
                (None, None) => true,
                #[cfg(feature = "keyexpr-wildcard-double")]
                (Some(&"**"), _) => {
                    intersect_by_descent(&a[1..], b)
                        || match b.first() {
                            None => false,
                            Some(next) if is_verbatim_chunk(next) => false,
                            Some(_) => intersect_by_descent(a, &b[1..]),
                        }
                }
                #[cfg(feature = "keyexpr-wildcard-double")]
                (_, Some(&"**")) => intersect_by_descent(b, a),
                (None, _) | (_, None) => false,
                (Some(ap), Some(bp)) => {
                    chunk_intersects(ap, bp) && intersect_by_descent(&a[1..], &b[1..])
                }
            }
        }

        #[cfg(feature = "keyexpr-includes")]
        pub(super) fn includes_by_descent(a: &[&str], b: &[&str]) -> bool {
            match (a.first(), b.first()) {
                (None, None) => true,
                #[cfg(feature = "keyexpr-wildcard-double")]
                (Some(&"**"), _) => {
                    includes_by_descent(&a[1..], b)
                        || match b.first() {
                            None => false,
                            Some(next) if is_verbatim_chunk(next) => false,
                            Some(_) => includes_by_descent(a, &b[1..]),
                        }
                }
                #[cfg(feature = "keyexpr-wildcard-double")]
                (_, Some(&"**")) => false,
                (None, _) | (_, None) => false,
                (Some(ap), Some(bp)) => {
                    chunk_includes(ap, bp) && includes_by_descent(&a[1..], &b[1..])
                }
            }
        }

        /// The glob walk of a pattern over a literal key, with one `**` backtrack frame.
        pub(super) fn matches_by_walk(pattern: &[&str], target: &[&str]) -> bool {
            let mut pi = 0;
            let mut ti = 0;
            #[cfg(feature = "keyexpr-wildcard-double")]
            let mut frame: Option<(usize, usize)> = None;
            while ti < target.len() {
                if pi < pattern.len() {
                    let pat = pattern[pi];
                    #[cfg(feature = "keyexpr-wildcard-double")]
                    if pat == "**" {
                        frame = Some((pi, ti));
                        pi += 1;
                        continue;
                    }
                    #[cfg(feature = "keyexpr-wildcard-single")]
                    if pat == "*" && !is_verbatim_chunk(target[ti]) {
                        pi += 1;
                        ti += 1;
                        continue;
                    }
                    if chunk_matches(pat, target[ti]) {
                        pi += 1;
                        ti += 1;
                        continue;
                    }
                }
                #[cfg(feature = "keyexpr-wildcard-double")]
                if let Some((saved_pi, saved_ti)) = frame {
                    if is_verbatim_chunk(target[saved_ti]) {
                        return false;
                    }
                    frame = Some((saved_pi, saved_ti + 1));
                    ti = saved_ti + 1;
                    pi = saved_pi + 1;
                    continue;
                }
                return false;
            }
            #[cfg(feature = "keyexpr-wildcard-double")]
            while pi < pattern.len() && pattern[pi] == "**" {
                pi += 1;
            }
            pi == pattern.len()
        }
    }

    /// The scan `text_is_a_key` was before the facts were read in one pass, kept here as the
    /// reference the facts are held to.
    fn text_is_a_key_by_the_old_scan(text: &str) -> bool {
        let bytes = text.as_bytes();
        if bytes.is_empty() || bytes[0] == b'/' || bytes[bytes.len() - 1] == b'/' {
            return false;
        }
        let mut slashes = 0usize;
        let mut previous = 0u8;
        for &byte in bytes {
            if byte == b'/' {
                if previous == b'/' {
                    return false;
                }
                slashes += 1;
            }
            previous = byte;
        }
        !crate::bounded::ENFORCES_CAPACITY || slashes < MAX_KEYEXPR_CHUNKS
    }

