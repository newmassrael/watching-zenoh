/// Whether some key matches both `a` and `b`; either may be a pattern, and the answer is
/// symmetric. zenoh's `intersects`. See the module docs for what it refuses.
pub fn keyexpr_intersects(a: &str, b: &str) -> bool {
    #[cfg(test)]
    INTERSECT_WALKS.with(|walks| walks.set(walks.get() + 1));
    generated::keyexpr_intersects::keyexpr_intersects(
        a.as_bytes(),
        b.as_bytes(),
        WILD_SINGLE,
        WILD_DOUBLE,
        WILD_DSL,
        crate::bounded::ENFORCES_CAPACITY,
        CHUNK_BOUND,
    )
}

/// Whether every key `subset` matches is matched by `superset`: zenoh's `includes` (zenoh-pico
/// `_z_keyexpr_includes`, `left` includes `right`). Directional: an ACL rule `deny home/*` does
/// not cover a `home/**` declaration, which it does intersect. See the module docs for what it
/// refuses.
#[cfg(feature = "keyexpr-includes")]
pub fn keyexpr_includes(superset: &str, subset: &str) -> bool {
    generated::keyexpr_includes::keyexpr_includes(
        superset.as_bytes(),
        subset.as_bytes(),
        WILD_SINGLE,
        WILD_DOUBLE,
        WILD_DSL,
        crate::bounded::ENFORCES_CAPACITY,
        CHUNK_BOUND,
    )
}

/// Whether the pattern `pattern` matches the key `target`, `target` read as a literal key: a `*`
/// in it is a byte, not a wildcard, so `demo/a` does not match `demo/*` (which it intersects). A
/// subscriber's glob over a published key. See the module docs for what it refuses.
pub fn keyexpr_matches(pattern: &str, target: &str) -> bool {
    generated::keyexpr_matches::keyexpr_matches(
        pattern.as_bytes(),
        target.as_bytes(),
        WILD_SINGLE,
        WILD_DOUBLE,
        WILD_DSL,
        crate::bounded::ENFORCES_CAPACITY,
        CHUNK_BOUND,
    )
}

/// Whether `keyexpr` contains a wildcard chunk (`*`, `**`, or the `$*`
/// dollar-star) — the single wildcard-PRESENCE predicate, the companion of the
/// wildcard-MATCH predicates above. `*` (ASCII 0x2A) is the sole wildcard lead
/// byte and, being ASCII, cannot occur inside a multi-byte UTF-8 sequence
/// (continuation / lead bytes are all >= 0x80), so a raw byte scan is correct
/// on arbitrary UTF-8. This is the SSOT for "is this a wildcard update / query"
/// — callers must not re-open-code `.contains('*')` (the same scan
/// [`crate::keyexpr_prefix::NonWildKeyExpr::new`] rejects on, and zenoh
/// `is_wild`, `key_expr/borrowed.rs:133`). `const` so a static keyexpr literal
/// can be classified at compile time.
pub const fn is_wild(keyexpr: &str) -> bool {
    let mut rest = keyexpr.as_bytes();
    while let [first, tail @ ..] = rest {
        if *first == b'*' {
            return true;
        }
        rest = tail;
    }
    false
}

/// Whether the keyexpr `candidate` intersects the keyexpr `target`, both as text: the question
/// [`keyexpr_intersects`] answers, under the name its text-holding callers have used since the
/// matcher took chunks.
pub fn keyexpr_intersects_text(candidate: &str, target: &str) -> bool {
    keyexpr_intersects(candidate, target)
}

/// What is true of a key's text, read in one pass and kept: whether it holds a wildcard, and
/// whether it is a key the matchers accept (no empty chunk, and on the fixed backing no deeper
/// than [`MAX_KEYEXPR_CHUNKS`]).
///
/// A key that does not change between questions is asked about once. A queryable's pattern is
/// fixed from its declaration and a query's key is fixed from its decode, and every match
/// between the two used to scan both again (a wildcard search on each, then a validity pass on
/// a hit). The facts are the same answers, computed where the text is made.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct KeyFacts {
    wild: bool,
    key: bool,
}

impl KeyFacts {
    /// The facts of `text`: the SCE `algorithm` document `sources/algorithms/key_facts.scxml`,
    /// whose record is `key_facts_schema.scxml`.
    #[inline(never)]
    pub fn of(text: &str) -> Self {
        let facts = generated::key_facts::key_facts(
            text.as_bytes(),
            crate::bounded::ENFORCES_CAPACITY,
            CHUNK_BOUND,
        );
        Self {
            wild: facts.wild,
            key: facts.key,
        }
    }

    /// Whether the text is a key the matchers accept: no empty chunk, and on the fixed backing
    /// no deeper than [`MAX_KEYEXPR_CHUNKS`].
    pub const fn is_key(self) -> bool {
        self.key
    }

    /// Whether the key of these facts intersects ITSELF, which is what a reply keyed exactly as
    /// its query is asked: the answer [`keyexpr_intersects`] gives for the same text on both
    /// sides, with no scan unless a wildcard makes the walk necessary.
    pub fn intersects_itself(self, text: &str) -> bool {
        if self.wild {
            keyexpr_intersects(text, text)
        } else {
            self.key
        }
    }
}

/// [`keyexpr_intersects`] for two keys whose [`KeyFacts`] are already known: the same answer,
/// with no scan of either text unless a wildcard makes the walk necessary.
pub fn keyexpr_intersects_text_with(
    candidate: &str,
    candidate_facts: KeyFacts,
    target: &str,
    target_facts: KeyFacts,
) -> bool {
    if !(candidate_facts.wild || target_facts.wild) {
        return candidate == target && target_facts.key;
    }
    keyexpr_intersects(candidate, target)
}

