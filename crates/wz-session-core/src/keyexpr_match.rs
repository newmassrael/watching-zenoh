    /// The shapes a router asks of the matchers once a message: a declaration
    /// with a wildcard against the message's key, matching and not.
    /// Each pair is (declaration, key, intersects, includes).
    #[cfg(all(
        feature = "keyexpr-wildcard-single",
        feature = "keyexpr-wildcard-double",
        feature = "keyexpr-dollar-star",
        feature = "keyexpr-includes"
    ))]
    const ROUTER_SHAPES: [(&str, &str, bool, bool); 10] = [
        ("home/**", "home/kitchen/temp", true, true),
        ("home/*/temp", "home/kitchen/temp", true, true),
        ("**/temp", "home/kitchen/temp", true, true),
        ("home/kitchen/*", "home/garage/temp", false, false),
        ("home/**", "office/desk/lamp", false, false),
        ("demo/**/pose", "demo/robot/arm/joint/pose", true, true),
        ("a/**/b/**/c", "a/x/b/y/z/c", true, true),
        ("a/**/b/**/c", "a/x/b/y/z/d", false, false),
        (
            "@/5a1c0ffee001/**",
            "@/5a1c0ffee001/peer/status/connect",
            true,
            true,
        ),
        ("robot/$*arm/**", "robot/leftarm/joint/0", true, true),
    ];

    /// Instrument, not a gate: the time and the answers of the per-message
    /// relations over [`ROUTER_SHAPES`], each asked `WZ_KEYEXPR_ROUNDS` times
    /// (default 2,000,000). Read the instructions per run with `perf stat`
    /// beside the time, because time moves with code layout between builds.
    #[cfg(all(
        feature = "keyexpr-wildcard-single",
        feature = "keyexpr-wildcard-double",
        feature = "keyexpr-dollar-star",
        feature = "keyexpr-includes"
    ))]
    #[test]
    #[ignore = "instrument: run with --ignored --nocapture"]
    fn the_matchers_measured_on_the_shapes_a_router_meets() {
        use std::hint::black_box;
        let rounds: usize = std::env::var("WZ_KEYEXPR_ROUNDS")
            .ok()
            .and_then(|r| r.parse().ok())
            .unwrap_or(2_000_000);
        for (declaration, key, intersects, includes) in ROUTER_SHAPES {
            assert_eq!(
                keyexpr_intersects(declaration, key),
                intersects,
                "intersects {declaration:?} {key:?}"
            );
            assert_eq!(
                keyexpr_includes(declaration, key),
                includes,
                "includes {declaration:?} {key:?}"
            );
        }
        // The generated relations against the hand-written ones they replaced, asked the way their
        // callers asked them: the message's key split once, the declaration split at each call.
        // One process and blocks that alternate which goes first, so a change of load on a
        // shared host falls on both.
        let keys: [([&str; 40], usize); ROUTER_SHAPES.len()] = core::array::from_fn(|shape| {
            split_for_reference(ROUTER_SHAPES[shape].1).expect("a well formed key")
        });
        let generated = |count: usize| {
            let started = std::time::Instant::now();
            let mut met = 0usize;
            for _ in 0..count {
                for (declaration, key, _, _) in ROUTER_SHAPES {
                    met += usize::from(keyexpr_intersects(black_box(declaration), black_box(key)));
                    met += usize::from(keyexpr_includes(black_box(declaration), black_box(key)));
                }
            }
            (started.elapsed().as_nanos(), met)
        };
        let hand_written = |count: usize| {
            let started = std::time::Instant::now();
            let mut met = 0usize;
            for _ in 0..count {
                for ((declaration, _, _, _), (chunks, len)) in ROUTER_SHAPES.iter().zip(&keys) {
                    let key = black_box(&chunks[..*len]);
                    let Some((split, split_len)) = split_for_reference(black_box(declaration))
                    else {
                        continue;
                    };
                    let declaration = &split[..split_len];
                    met += usize::from(reference::intersect_by_descent(declaration, key));
                    met += usize::from(reference::includes_by_descent(declaration, key));
                }
            }
            (started.elapsed().as_nanos(), met)
        };
        const BLOCKS: usize = 10;
        let per_block = (rounds / BLOCKS).max(1);
        let (mut generated_ns, mut hand_ns) = (0u128, 0u128);
        let (mut generated_met, mut hand_met) = (0usize, 0usize);
        for block in 0..BLOCKS {
            for generated_first in [block % 2 == 0, block % 2 == 1] {
                if generated_first {
                    let (ns, met) = generated(per_block);
                    generated_ns += ns;
                    generated_met += met;
                } else {
                    let (ns, met) = hand_written(per_block);
                    hand_ns += ns;
                    hand_met += met;
                }
            }
        }
        assert_eq!(generated_met, hand_met, "the two matchers disagree");
        let calls = (BLOCKS * per_block * ROUTER_SHAPES.len() * 2) as f64;
        std::println!(
            "keyexpr_matchers calls={calls} met={generated_met} generated_ns_per_call={:.2} \
             hand_written_ns_per_call={:.2}",
            generated_ns as f64 / calls,
            hand_ns as f64 / calls
        );
    }
