/// Minimal TCP driver. Reads/writes length-prefixed frames on a
/// single TcpStream using the Zenoh streamed-link wire envelope:
/// **2-byte little-endian length** + payload bytes. This matches
/// zenoh-pico's `_z_link_send_t_msg` /
/// `_z_link_recv_t_msg_cap_flow_stream` (`Z_LINK_CAP_FLOW_STREAM`
/// branch) at zenoh-pico/src/transport/common/{tx,rx}.c with
/// `_Z_MSG_LEN_ENC_SIZE = 2` (zenoh-pico/include/zenoh-pico/
/// protocol/definitions/core.h:32), and bounds the per-frame
/// payload to 65535 bytes which is also the upstream
/// `Z_BATCH_UNICAST_SIZE` ceiling.
///
/// R121h: the wire envelope is now expressed by
/// `sources/codecs/stream_envelope.scxml` (SCE codec_kind) and
/// rendered into `wz_codecs::stream_envelope::StreamEnvelope`. The
/// driver invokes the generated encoder on `send` and the generated
/// decoder on `poll_event` so the codec catalog is the single
/// source of truth for the on-wire shape. The 2-byte prefix read
/// at the start of `poll_event` is unavoidable until SCE exposes a
/// codec-level `MIN_FRAME_BYTES` associated constant (the wire
/// shape needs a length to size the second `read_exact`, and the
/// codec's `decode` requires the full frame in the cursor before
/// it can run). The duplication is bounded to a 2-byte `[u8; 2]`
/// length sniff; the structural decode runs through the codec.
#[cfg(feature = "transport-link-tcp")]
pub struct TcpDriver {
    stream: Option<TcpStream>,
    /// R265 — partial-read state machine for the cancel-safe
    /// poll_event implementation. Carries the in-flight length
    /// prefix or payload bytes across `tokio::select!` cancellations
    /// of `poll_event`, so the next iteration resumes from the
    /// last byte offset rather than re-syncing from a mid-frame
    /// socket cursor. See [`ReadState`] for the state graph.
    read_state: ReadState,
}

/// R265 — cancel-safe partial-read state for [`TcpDriver::poll_event`]
/// (the same shape is mirrored on `wz-ap-demo`'s `InboundReadDriver`).
///
/// Background. The `tokio::io::AsyncReadExt::read_exact` future loops
/// internally over `.read()` calls; if its outer future is dropped
/// (e.g. by `tokio::select!` losing the race) any bytes already
/// consumed from the socket are discarded. For a length-prefixed
/// envelope (2 byte length, N byte payload) that means the next
/// poll re-reads from the socket cursor at an offset that no longer
/// aligns with a frame boundary, and the decoder mis-interprets
/// payload bytes as the next frame's length. R264 fixture surfaced
/// this when a sub-second sweep cadence inside `drive_session_until_-
/// terminal` race-cancelled `poll_and_dispatch_one` 10x/s.
///
/// Fix shape. The state machine keeps the partial-read buffers in
/// `&mut self`, and the only `.await` point per state transition is
/// a single `.read()` syscall. `AsyncReadExt::read` is documented as
/// cancel-safe (no bytes consumed if the future is dropped before
/// completion), so dropping `poll_event` mid-state leaves the
/// captured offset / buffer intact for the next invocation.
#[cfg(feature = "transport-link-tcp")]
#[derive(Default)]
pub(crate) enum ReadState {
    /// No partial read in flight. Next `poll_event` enters `Length` and begins
    /// reading the length prefix, whose WIDTH (2-byte u16 universal / 4-byte u32
    /// lowlatency) is fixed from the link's lowlatency flag at that transition.
    #[default]
    Idle,
    /// Length prefix partially read. `prefix[..offset]` holds the bytes consumed
    /// so far; `offset < width` (`width` is 2 or 4). Once `offset == width`, the
    /// prefix is decoded and the state transitions to `Payload` with a sized
    /// buffer.
    Length {
        prefix: [u8; 4],
        offset: usize,
        width: usize,
    },
    /// Payload partially read into `frame[..offset]`; `frame` includes the
    /// `prefix_width`-byte length prefix at `frame[..prefix_width]` so the u16
    /// codec decode at frame-complete operates on the wire-shape bytes verbatim
    /// (the 4-byte u32 lowlatency path takes the payload tail directly).
    /// `offset < frame.len()` while reading; `offset == frame.len()` means the
    /// frame is complete and the state machine emits a `LinkEvent::Rx` +
    /// transitions back to `Idle` on the next iteration.
    Payload {
        frame: Vec<u8>,
        offset: usize,
        prefix_width: usize,
    },
}

/// R311et — shared cancel-safe framing read used by both [`TcpDriver`]
/// (the unified acceptor/adapter-path driver) and
/// [`link_pipeline::TcpReadDriver`] (the split read half on the production
/// session-open path). Reads one length-prefixed [`StreamEnvelope`] frame
/// from `src`, advancing `read_state` across `tokio::select!` cancellations
/// (each `.await` is a single cancel-safe `.read()` syscall), and returns
/// the codec-decoded payload as [`LinkEvent::Rx`] — or [`LinkEvent::Lost`]
/// on EOF / IO / codec error, resetting `read_state` to `Idle` so a retry
/// path does not inherit a partial buffer.
///
/// Extracted from the pre-R311et `TcpDriver::poll_event` body verbatim so
/// the framing state machine has a single home. `wz-ap-demo`'s duplicated
/// `InboundReadDriver` copy retires when the demo consumes `link_pipeline`
/// (R311ev).
///
/// R2288 (open-debt item 610) — WHERE THE CODEC OWNS THE WIRE SHAPE, AND WHERE
/// THIS FUNCTION DOES. This comment used to claim the read half was
/// "codec-routed (the `StreamEnvelope` decode is the single source of truth,
/// not a hand-rolled prefix strip)". Measured, the opposite was true in both
/// halves of that sentence: this loop reads the length prefix by hand
/// (`u16::from_le_bytes`) because a stream cannot be framed without doing so
/// first, and the `StreamEnvelope::decode` that followed re-read that same
/// number off the buffer this loop had just sized from it, returning a payload
/// byte-identical to the frame tail. It adjudicated nothing, and its `Err` arm
/// could not fire.
///
/// The codec is still the single source of truth for the shape -- on the WRITE
/// side, where it is the thing that emits the bytes ([`TcpDriver::send`] and
/// [`stream_link::StreamWriteDriver::send_blocking`] both encode through it).
/// What binds this reader to that writer is a test rather than a dead runtime
/// arm: `the_writers_codec_frames_what_this_reader_unframes` feeds this
/// function exactly what the codec encodes, so a codegen change to the prefix
/// width or endianness reds a lane instead of silently desynchronising the two
/// halves.
///
/// Every `LinkEvent::Lost` this function can return carries a `REACHED-BY:`
/// marker naming the test that fires it, and
/// `scripts/lib/framing_refusal_reachability_gate.py` derives the population
/// from this body rather than from a list -- an unmarked refusal is RED, which
/// is what item 610 was: an arm nobody could reach and nobody was measuring.
#[cfg(feature = "transport-link-tcp")]
pub(crate) async fn poll_framed<S>(
    read_state: &mut ReadState,
    src: &mut S,
    lowlatency: bool,
) -> LinkEvent
where
    S: tokio::io::AsyncRead + Unpin,
{
    loop {
        match read_state {
            ReadState::Idle => {
                // transport-lowlatency — a negotiated + Established lowlatency link
                // frames with a 4-byte LE u32 prefix (zenoh
                // `unicast/lowlatency/link.rs`); every other frame (universal + the
                // handshake) keeps the 2-byte u16 prefix. The width is fixed here,
                // at frame start, so a flag flip between frames never splits a
                // prefix mid-read.
                let width = if lowlatency { 4 } else { 2 };
                *read_state = ReadState::Length {
                    prefix: [0u8; 4],
                    offset: 0,
                    width,
                };
            }
            ReadState::Length {
                prefix,
                offset,
                width,
            } => match src.read(&mut prefix[*offset..*width]).await {
                Ok(0) => {
                    *read_state = ReadState::Idle;
                    // REACHED-BY: a_stream_that_ends_before_the_prefix_loses_the_link (PeerClosed)
                    return LinkEvent::Lost {
                        cause: LostCause::PeerClosed,
                    };
                }
                Ok(n) => {
                    *offset += n;
                    if *offset == *width {
                        let w = *width;
                        let payload_len = if w == 4 {
                            u32::from_le_bytes([prefix[0], prefix[1], prefix[2], prefix[3]])
                                as usize
                        } else {
                            u16::from_le_bytes([prefix[0], prefix[1]]) as usize
                        };
                        // transport-lowlatency — the 4-byte prefix is an untrusted
                        // u32; bound it before allocating, exactly as zenoh's
                        // read_with_link rejects an over-max batch ("Batch len is
                        // invalid. Received {n} but negotiated max len is {len}").
                        // The u16 path is inherently capped by its type; the u32
                        // path must not allocate an attacker-chosen ~4 GiB. A legit
                        // lowlatency frame rides the negotiated batch (<= u16::MAX,
                        // matching send_blocking's outbound u16::MAX cap), so this
                        // never rejects a well-formed peer.
                        if payload_len > u16::MAX as usize {
                            *read_state = ReadState::Idle;
                            // REACHED-BY: lowlatency_rx_rejects_oversize_u32_prefix (PeerClosed)
                            return LinkEvent::Lost {
                                cause: LostCause::PeerClosed,
                            };
                        }
                        let mut frame = vec![0u8; w + payload_len];
                        frame[..w].copy_from_slice(&prefix[..w]);
                        *read_state = ReadState::Payload {
                            frame,
                            offset: w,
                            prefix_width: w,
                        };
                    }
                }
                Err(_) => {
                    *read_state = ReadState::Idle;
                    // REACHED-BY: an_io_error_reading_the_prefix_loses_the_link (OsError)
                    return LinkEvent::Lost {
                        cause: LostCause::OsError,
                    };
                }
            },
            ReadState::Payload {
                frame,
                offset,
                prefix_width,
            } => {
                if *offset == frame.len() {
                    // Frame complete. Take the buffer out before reading it so
                    // the state reset is visible on every exit from this arm.
                    let w = *prefix_width;
                    let bytes = std::mem::take(frame);
                    *read_state = ReadState::Idle;
                    // R2288 (open-debt item 610) — THE PAYLOAD IS THE FRAME TAIL,
                    // AT BOTH PREFIX WIDTHS. Until this round the 2-byte arm
                    // re-decoded the completed frame through
                    // `StreamEnvelope::decode` and mapped its `Err` to
                    // `Lost { PeerClosed }`, which read as "wz refuses a malformed
                    // batch here". MEASURED, it refused nothing:
                    //
                    //   * `env.payload` came back BYTE-IDENTICAL to `&bytes[2..]`,
                    //     because the length the codec re-reads is the length this
                    //     loop just wrote into `bytes[..2]` and sized the buffer
                    //     from. Two reads of one number always agree.
                    //   * so the `Err` arm had no path to being true, and a guard
                    //     that cannot fire documents a check nobody performs --
                    //     R2268's dead guard, in another file.
                    //
                    // The other repair item 610 offered -- keep the arm and make
                    // it reachable by handing the codec a PARTIAL buffer so it
                    // adjudicates the length mismatch -- was measured and is NOT
                    // available: `decode` indexes `raw[2..2 + payload_len]` after
                    // checking only `remaining() >= 2`, so a short frame PANICS
                    // instead of returning `NeedMoreBytes`. A framing layer cannot
                    // ask it that question.
                    //
                    // ⚠ THIS IS NOT "malformed input can no longer lose the link",
                    // which would diverge from upstream: zenoh answers a batch it
                    // cannot decode with `zerror!("{}: decoding error")`, and the
                    // `?` on it ends the rx task (`unicast/universal/rx.rs`). It is
                    // that the refusal lives ONE LAYER UP, where the bytes mean
                    // something -- `parse_inbound` -> `InboundParseError` is wz's
                    // counterpart to upstream's `batch.decode()`, and it is fatal
                    // there for the same reason. What THIS layer owns is FRAMING,
                    // and a completed frame is by construction well framed; its
                    // only failures are running out of bytes and the OS, both of
                    // which still return `Lost`.
                    //
                    // The wire shape stays codec-owned where a codec can own it:
                    // `TcpDriver::send` and `StreamWriteDriver::send_blocking` both
                    // ENCODE through `StreamEnvelope`, and
                    // `the_writers_codec_frames_what_this_reader_unframes` pins the
                    // two halves together -- so a codegen change to the prefix
                    // width or endianness reds a test instead of silently
                    // desynchronising them. That is a live contract; the deleted
                    // arm was not one.
                    let payload = &bytes[w..];
                    // R2271 (open-debt item 577) — A ZERO-LENGTH BATCH IS A BATCH
                    // OF NO MESSAGES, and reading it means doing nothing. Passing
                    // the empty payload up made the parser meet it as
                    // `InboundParseError::Empty` and the link go
                    // `LinkLost(PeerClosed)`: one harmless malformed batch from a
                    // peer ended the session.
                    //
                    // MEASURED against both implementations this one replaces,
                    // because "whose defect is it" is not the question -- "must a
                    // receiver survive it" is:
                    //
                    //   * zenoh (Rust) reads a batch with `while !batch.is_empty()`
                    //     (`zenoh-transport`, `unicast/universal/rx.rs`),
                    //     `while reader.can_read()` on the lowlatency path, and
                    //     `while !batch.is_empty()` again for multicast. An empty
                    //     batch runs the body zero times and returns `Ok(())`.
                    //   * zenoh-pico reads one with `while (_z_zbuf_len(&zbuf) > 0)`
                    //     (`src/transport/unicast/read.c`,
                    //     `_z_unicast_process_messages`, which is what the
                    //     steady-state read task calls). Zero iterations,
                    //     `_Z_RES_OK`, session kept.
                    //
                    // Both survive; only this did not. Skipping back to the next
                    // frame is the same sentence as their `while`, and it loses
                    // nothing: no transport message is zero bytes long, so an
                    // empty payload can only mean "no messages".
                    //
                    // ⚠ NOT a busy loop. Every pass through `Idle` reaches an
                    // awaited `src.read()`, so an endless stream of empty batches
                    // costs one syscall each and stays cancel-safe -- exactly what
                    // it costs the two implementations above.
                    if payload.is_empty() {
                        continue;
                    }
                    return LinkEvent::Rx(RxFrame::new(payload.to_vec()));
                }
                match src.read(&mut frame[*offset..]).await {
                    Ok(0) => {
                        *read_state = ReadState::Idle;
                        // REACHED-BY: a_frame_truncated_mid_payload_loses_the_link (PeerClosed)
                        return LinkEvent::Lost {
                            cause: LostCause::PeerClosed,
                        };
                    }
                    Ok(n) => {
                        *offset += n;
                    }
                    Err(_) => {
                        *read_state = ReadState::Idle;
                        // REACHED-BY: an_io_error_reading_the_payload_loses_the_link (OsError)
                        return LinkEvent::Lost {
                            cause: LostCause::OsError,
                        };
                    }
                }
            }
        }
    }
}

#[cfg(feature = "transport-link-tcp")]
impl TcpDriver {
    /// Wrap an already-open TcpStream (acceptor side). The
    /// `open()` method is a no-op for this constructor.
    pub fn from_stream(stream: TcpStream) -> Self {
        Self {
            stream: Some(stream),
            read_state: ReadState::Idle,
        }
    }

    /// R311es — dial an outbound TCP connection to `addr` and wrap the
    /// resulting stream (Initiator side). This is the dial half of the
    /// scouting locator seam: a [`wz_session_core::locator::ParsedLocator`]
    /// with `proto = Tcp` carries the numeric `addr` this constructor
    /// connects to, mirroring [`from_stream`] for the acceptor side.
    ///
    /// `open()` is a no-op afterwards because the stream is already
    /// connected — same post-condition as `from_stream`. Connect-timeout
    /// / retry tuning is the caller's concern (compose a
    /// `tokio::time::timeout` around this); the kernel default applies
    /// otherwise, matching `wz-ap-demo`'s `establish_link` (runner.rs).
    ///
    /// R311et — the actual socket dial routes through the single raw-dial
    /// primitive [`link_pipeline::dial_tcp`], so this unified-driver
    /// constructor and the split session-open pipeline
    /// ([`link_pipeline::wire_tcp_stream`]) share one connect path. The
    /// mode-agnostic `dial_locator(AnyLocator)` dispatcher (R311eu)
    /// dispatches a numeric `Proto::Tcp` endpoint to `dial_tcp` and then splits the
    /// stream for the FSM, rather than burying the stream inside this
    /// driver — hence the raw-dial seam lives in `link_pipeline`.
    pub async fn connect(addr: SocketAddr) -> io::Result<Self> {
        // R311y236 — the driver-level connect takes a bare addr (no locator, so
        // no `#iface=`); pass `None` for the interface bind.
        Ok(Self::from_stream(
            link_pipeline::dial_tcp(addr, None).await?,
        ))
    }
}

#[cfg(feature = "transport-link-tcp")]
impl LinkDriver for TcpDriver {
    async fn open(&mut self) -> io::Result<()> {
        // R51 baseline: caller passes an already-open stream via
        // from_stream. Outbound dial flow (TcpStream::connect) lands
        // when the session FSM Initiator path is wired.
        if self.stream.is_some() {
            Ok(())
        } else {
            Err(io::Error::new(
                io::ErrorKind::NotConnected,
                "TcpDriver::open requires from_stream constructor",
            ))
        }
    }

    async fn send(&mut self, frame: &TxFrame<'_>, _reliability: Reliability) -> io::Result<()> {
        let stream = self
            .stream
            .as_mut()
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotConnected, "no stream"))?;
        let payload_len: u16 = frame
            .bytes
            .len()
            .try_into()
            .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "frame > 65535 bytes"))?;
        // Borrowed zero-copy view over the in-scope frame buffer — the
        // SCE borrowed codec encodes directly from `frame.bytes` with
        // no owned copy (the envelope lives only until `encode_to_vec`).
        let envelope = StreamEnvelope {
            payload_len,
            payload: frame.bytes,
        };
        let wire = envelope.encode_to_vec();
        stream.write_all(&wire).await?;
        stream.flush().await?;
        Ok(())
    }

    async fn close(&mut self) -> io::Result<()> {
        if let Some(mut s) = self.stream.take() {
            s.shutdown().await?;
        }
        Ok(())
    }

    async fn poll_event(&mut self) -> LinkEvent {
        // R311et — the cancel-safe framing state machine lives in the
        // shared [`poll_framed`] free fn so the split read half
        // ([`link_pipeline::TcpReadDriver`]) decodes identical wire
        // bytes. The `stream.is_none()` (closed) guard stays here because
        // it is `TcpDriver`-specific (the split read half always owns its
        // `OwnedReadHalf`).
        match self.stream.as_mut() {
            // TcpDriver is the unified acceptor/adapter driver; the lowlatency
            // open helpers wire via `wire_dialed_link` -> `StreamReadDriver`, not
            // this path, so it always reads the universal 2-byte prefix.
            Some(stream) => poll_framed(&mut self.read_state, stream, false).await,
            None => LinkEvent::Lost {
                cause: LostCause::PeerClosed,
            },
        }
    }
}

/// UDP datagram driver. R51 baseline assumes one peer; each
/// `send()` writes one datagram, each `poll_event()` receives one
/// datagram. No framing prefix — UDP preserves message boundaries.
/// Honors `Reliability::BestEffort` (the natural UDP semantic) and
/// silently drops the hint on `Reliability::Reliable` (the session
/// FSM's responsibility — UDP cannot enforce reliability at the
/// link layer).
#[cfg(feature = "transport-link-udp")]
pub struct UdpDriver {
    socket: Option<UdpSocket>,
    peer: Option<SocketAddr>,
}

#[cfg(feature = "transport-link-udp")]
impl UdpDriver {
    /// Wrap a bound UdpSocket + the remote peer the driver
    /// `send()` targets. R51 baseline: caller establishes the
    /// (socket, peer) pair externally; future rounds add an
    /// outbound-discovery + scout-driven peer-selection path.
    pub fn from_socket(socket: UdpSocket, peer: SocketAddr) -> Self {
        Self {
            socket: Some(socket),
            peer: Some(peer),
        }
    }

    /// R311es — bind an ephemeral local UDP socket and target `peer`
    /// for unicast `send()` (Initiator side). This is the UDP dial half
    /// of the scouting locator seam: a
    /// [`wz_session_core::locator::ParsedLocator`] with `proto = Udp`
    /// carries the numeric `peer` this constructor targets, mirroring
    /// [`TcpDriver::connect`] for the datagram transport.
    ///
    /// Distinct from [`bind_multicast_v4`], which joins a scouting group;
    /// this dials a single already-discovered unicast peer. The local
    /// bind address family mirrors `peer` so an IPv6 locator binds an
    /// IPv6 socket (a v4-bound socket cannot reach a v6 peer).
    pub async fn connect(peer: SocketAddr) -> io::Result<Self> {
        let bind_addr: SocketAddr = match peer {
            SocketAddr::V4(_) => (std::net::Ipv4Addr::UNSPECIFIED, 0).into(),
            SocketAddr::V6(_) => (std::net::Ipv6Addr::UNSPECIFIED, 0).into(),
        };
        let socket = UdpSocket::bind(bind_addr).await?;
        Ok(Self::from_socket(socket, peer))
    }

    /// R311en — bind a UDP socket on a multicast group and join it,
    /// returning a driver whose `send()` multicasts to the group. This
    /// is the scouting link transport (docs/scouting-fsm.md §1.2): the
    /// default zenoh scout group is `224.0.0.224:7446`
    /// (`Z_CONFIG_MULTICAST_LOCATOR_DEFAULT`).
    ///
    /// The four setup steps must stay consistent, which is why they are
    /// folded into one constructor rather than left to the caller as
    /// `from_socket` does:
    ///   1. SO_REUSEADDR + SO_REUSEPORT before bind — a multicast group
    ///      port is inherently multi-listener: every zenoh peer on the
    ///      host binds the SAME `0.0.0.0:port` to receive the group.
    ///      Without both reuse options the second binder fails with
    ///      `EADDRINUSE`, so co-locating a wz multicast receiver with a
    ///      foreign zenoh-pico peer (the `pico -> wz` dial-in) is
    ///      impossible.
    ///   2. bind `0.0.0.0:port` (INADDR_ANY) — a socket bound to a
    ///      unicast address cannot receive datagrams addressed to the
    ///      group.
    ///   3. `join_multicast_v4(group, INADDR_ANY)` — subscribe on the
    ///      default interface; without the join the kernel drops group
    ///      datagrams even with the matching bind port.
    ///   4. `set_multicast_loop_v4(true)` — let a same-host peer (and
    ///      the loopback smoke test) observe the traffic; off by default
    ///      on some platforms.
    ///
    /// `peer` is set to `group:port` so `LinkDriver::send` writes the
    /// Scout datagram to the group.
    ///
    /// R311no — the reuse options require a pre-bind setsockopt, which
    /// `tokio::net::UdpSocket` does not expose (it only adopts an already
    /// bound std socket), so the socket is built through `socket2`
    /// (Socket -> `std::net::UdpSocket` -> tokio `from_std`). This
    /// matches zenoh-pico, which sets SO_REUSEADDR + SO_REUSEPORT
    /// unconditionally on its multicast listener before binding
    /// `0.0.0.0:port`
    /// (`vendor/zenoh-pico/src/link/transport/udp/udp_multicast_posix.c`
    /// :180 / :185 / :196). The earlier single-receiver scouting design
    /// deliberately avoided socket2; the `pico -> wz` multicast interop
    /// requirement is exactly the multi-listener case that decision
    /// anticipated, so socket2 now enters as a feature-gated production
    /// dep (scouting-active / transport-multicast).
    // Round C — generalised from `scouting-active`-only to also serve the
    // multicast TRANSPORT (`transport-multicast`): the bind + join + loop
    // setup is identical for the scout group and the multicast session
    // group (zenoh shares the `224.0.0.224:7446` locator for both). The
    // caller passes the group, so the same constructor builds the scout
    // driver and the multicast session driver.
    // R311y454 — `iface` is the `#iface=<name>` MULTICAST honor, the third and
    // last residual of the `locator-iface` atom. It pins BOTH directions on this
    // one socket, because this one socket does both: `imr_interface` on the join
    // (which interface's membership is installed) and `IP_MULTICAST_IF` (which
    // interface egress leaves by), the pair zenoh splits across its `mcast_sock`
    // (`multicast.rs:315-322`) and `ucast_sock` (`:264-282`). `None` keeps the
    // pre-R311y454 behaviour byte for byte.
    //
    // What `imr_interface` is NOT: a source filter. It selects the interface whose
    // membership is installed; it does not narrow which senders are accepted.
    // `INADDR_ANY` does not mean "every interface" either — the kernel resolves it
    // to exactly one via the routing table. So this change is implicit -> explicit,
    // not one -> many.
    #[cfg(any(
        feature = "scouting-active",
        feature = "scouting-responder",
        feature = "transport-multicast"
    ))]
    pub async fn bind_multicast_v4(
        group: std::net::Ipv4Addr,
        port: u16,
        cfg: McastSocketConfig<'_>,
    ) -> io::Result<Self> {
        use socket2::{Domain, Protocol, Socket, Type};

        // Resolve BEFORE touching the socket, so a bad `#iface=` fails without
        // leaving a half-configured group membership behind.
        let selector = match cfg.iface {
            Some(iface) => crate::link_interfaces::multicast_iface_selector_v4(iface)?,
            None => None,
        };
        // R311y832 — and resolve the extra `#join=` groups before it too, for
        // the same reason: a typo in the third of four groups must not leave
        // two memberships installed and the caller believing it has four.
        let extra = cfg.resolved_joins()?;

        // Step 1: REUSEADDR + REUSEPORT must be set before bind, and
        // tokio's UdpSocket exposes no pre-bind setsockopt hook, so the
        // socket is built through socket2 and adopted by tokio post-bind.
        let raw = Socket::new(Domain::IPV4, Type::DGRAM, Some(Protocol::UDP))?;
        raw.set_reuse_address(true)?;
        raw.set_reuse_port(true)?;
        // tokio requires the std socket to be non-blocking before adoption.
        raw.set_nonblocking(true)?;
        // Egress interface, set through socket2: tokio's `UdpSocket` wraps
        // `IP_ADD_MEMBERSHIP` and `IP_MULTICAST_LOOP` but NOT `IP_MULTICAST_IF`,
        // so this has to happen while the socket is still a `socket2::Socket`.
        // Independent of the bind address (`0.0.0.0` below) — `IP_MULTICAST_IF`
        // chooses the egress path, not the local name.
        if let Some(addr) = selector {
            raw.set_multicast_if_v4(&addr)?;
        }
        let bind_addr = SocketAddr::from((std::net::Ipv4Addr::UNSPECIFIED, port));
        raw.bind(&bind_addr.into())?;

        // Step 2 done by the bind above; steps 3-4 use tokio's wrappers.
        let socket = UdpSocket::from_std(raw.into())?;
        let membership_iface = selector.unwrap_or(std::net::Ipv4Addr::UNSPECIFIED);
        socket.join_multicast_v4(group, membership_iface)?;
        // R311y832 — `#join=` groups, joined IN ADDITION to the locator's own
        // and on the SAME socket, which is the whole point: one bound port
        // serving several groups (zenoh `multicast.rs:316-347`). The membership
        // interface is the locator's, not a per-group one — zenoh passes the
        // same `src_ip4` to every join in that loop.
        for g in &extra {
            socket.join_multicast_v4(*g, membership_iface)?;
        }
        socket.set_multicast_loop_v4(true)?;
        // R311y832 — the hop limit. Set on THIS socket because this
        // constructor's socket is the one that sends as well as receives (see
        // the doc above); zenoh splits the roles and sets it on its `ucast_sock`
        // (`multicast.rs:363`), which is the sending half there.
        if let Some(ttl) = cfg.ttl {
            socket.set_multicast_ttl_v4(ttl)?;
        }
        let peer = SocketAddr::from((group, port));
        Ok(Self {
            socket: Some(socket),
            peer: Some(peer),
        })
    }

    /// R311y454 — a SEND-ONLY multicast driver: an ephemeral local socket whose
    /// egress interface is pinned by `#iface=`, writing to `group:port`.
    ///
    /// This is the wz counterpart of zenoh's `ucast_sock` — the separate unicast
    /// socket its multicast link sends from (`zenoh-link-udp/src/multicast.rs:264-290`),
    /// distinct from the wildcard-bound `mcast_sock` it joins and reads on
    /// (`:293-322`). wz already had that split at a higher level: the router's
    /// egress spawns an ephemeral sender (`crate::multicast_glue`) while its
    /// ingress uses [`Self::bind_multicast_v4`]. What the egress half lacked was
    /// the interface pin, which is why it needs a constructor rather than a bare
    /// `UdpSocket::bind` — there is now a setsockopt between the bind and the
    /// driver, and one SSOT is better than the same three lines at each sender.
    ///
    /// No join: a sender needs no group membership. So this deliberately does NOT
    /// set `IP_MULTICAST_LOOP` either — a send-only socket never reads back its
    /// own traffic. (The bidirectional [`Self::bind_multicast_v4`] does set it,
    /// and that IS a divergence from upstream, which sets `IP_MULTICAST_LOOP`
    /// nowhere; it is load-bearing for wz's same-host tests, where the ZID
    /// self-echo gate is what keeps a node from admitting its own JOIN.)
    #[cfg(any(
        feature = "scouting-active",
        feature = "scouting-responder",
        feature = "transport-multicast"
    ))]
    pub async fn bind_multicast_tx_v4(
        group: std::net::Ipv4Addr,
        port: u16,
        cfg: McastSocketConfig<'_>,
    ) -> io::Result<Self> {
        use socket2::{Domain, Protocol, Socket, Type};

        let selector = match cfg.iface {
            Some(iface) => crate::link_interfaces::multicast_iface_selector_v4(iface)?,
            None => None,
        };
        // Without an iface this is exactly the `UdpSocket::bind((UNSPECIFIED, 0))`
        // the senders did before, so the un-narrowed path is unchanged.
        let raw = Socket::new(Domain::IPV4, Type::DGRAM, Some(Protocol::UDP))?;
        raw.set_nonblocking(true)?;
        if let Some(addr) = selector {
            raw.set_multicast_if_v4(&addr)?;
        }
        let bind_addr = SocketAddr::from((std::net::Ipv4Addr::UNSPECIFIED, 0));
        raw.bind(&bind_addr.into())?;
        let socket = UdpSocket::from_std(raw.into())?;
        // R311y832 — this is the SEND-only half, so the hop limit belongs here
        // most directly; it is zenoh's `ucast_sock`, the socket
        // `multicast.rs:363` sets the TTL on. `extra_joins` is deliberately not
        // read: a sender installs no membership.
        if let Some(ttl) = cfg.ttl {
            socket.set_multicast_ttl_v4(ttl)?;
        }
        Ok(Self {
            socket: Some(socket),
            peer: Some(SocketAddr::from((group, port))),
        })
    }

    /// R2219 — bind a UNICAST socket on `local`, ephemeral port, with no link
    /// peer: one of the sockets a scouting Hello may be elected to leave from
    /// (`ucast_sockets`, zenoh `net/runtime/orchestrator.rs:1112`).
    ///
    /// `peer` is deliberately `None`, which is not an omission. This socket has
    /// no link partner — its destination is a different asker on every datagram
    /// and arrives with the datagram — so it is reached through
    /// [`Self::send_datagram_to`] and never through [`LinkDriver::send`]. Giving
    /// it a peer it never sends to would make [`LinkDriver::open`] succeed on a
    /// driver that is not a link.
    ///
    /// The bind is on a CONCRETE address, never the wildcard: the whole point of
    /// the socket is that its source address is the one the elected interface
    /// carries, and a `0.0.0.0` bind hands that choice back to the routing table.
    ///
    /// Upstream's `bind_ucast_port` additionally sets the multicast TTL on these
    /// sockets (`orchestrator.rs:746`), and that is NOT mirrored, because there
    /// it is load-bearing for a second job this socket does not have: upstream
    /// SENDS its own Scouts to the group from the same sockets it answers from
    /// (`Runtime::scout`, `:292-303` passing one `sockets` to both halves). wz
    /// keeps the two apart — the asking half sends from
    /// [`Self::bind_multicast_tx_v4`], which does set the TTL. A hop limit on a
    /// socket that only ever unicasts is a setting with no reader.
    #[cfg(feature = "scouting-responder")]
    pub async fn bind_reply_unicast(local: std::net::IpAddr) -> io::Result<Self> {
        let socket = UdpSocket::bind(SocketAddr::from((local, 0))).await?;
        Ok(Self {
            socket: Some(socket),
            peer: None,
        })
    }

    /// R311y846 — write one datagram to an address OTHER than the driver's
    /// `peer`.
    ///
    /// [`LinkDriver::send`] targets `self.peer`, which for a multicast driver
    /// is the GROUP — correct for a Scout and wrong for the Hello that answers
    /// one. Upstream replies unicast to the asker
    /// (`socket.send_to(wbuf.as_slice(), peer)`, zenoh
    /// `net/runtime/orchestrator.rs:1168`) and it has to: a scouting node reads
    /// replies on the ephemeral unicast socket it sent FROM, so a Hello
    /// multicast to the group is not delivered where the asker is listening.
    ///
    /// Deliberately NOT a `LinkDriver` method. That trait's contract is a link
    /// with one peer; a per-datagram destination is the shared-medium seam, the
    /// send-side mirror of [`wz_session_core::link::RxFrame::src`].
    pub async fn send_datagram_to(&self, bytes: &[u8], dst: SocketAddr) -> io::Result<()> {
        let socket = self
            .socket
            .as_ref()
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotConnected, "no socket"))?;
        socket.send_to(bytes, dst).await?;
        Ok(())
    }

    /// The address this driver's socket is bound to.
    ///
    /// For a group-joined receiver that is `0.0.0.0:<group port>` — a wildcard,
    /// which is why it is NOT a self-echo discriminator on its own (see gate 3
    /// in `wz_session_core::scout_responder`, deliberately unlinked: that module
    /// is behind the two scouting CODEC features and an intra-doc link to it
    /// does not resolve in the default rustdoc). It is here so a caller can
    /// REPORT which socket answered, which is what an operator checks when a
    /// node is not being found.
    pub fn local_addr(&self) -> io::Result<SocketAddr> {
        self.socket
            .as_ref()
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotConnected, "no socket"))?
            .local_addr()
    }
}

#[cfg(feature = "transport-link-udp")]
impl LinkDriver for UdpDriver {
    async fn open(&mut self) -> io::Result<()> {
        if self.socket.is_some() && self.peer.is_some() {
            Ok(())
        } else {
            Err(io::Error::new(
                io::ErrorKind::NotConnected,
                "UdpDriver::open requires from_socket constructor",
            ))
        }
    }

    async fn send(&mut self, frame: &TxFrame<'_>, _reliability: Reliability) -> io::Result<()> {
        // UDP link layer is best-effort by definition; Reliability
        // hint is the session FSM's concern (it may resend on the
        // RELIABLE channel via a sequence-number window). Here we
        // just write the datagram.
        let socket = self
            .socket
            .as_ref()
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotConnected, "no socket"))?;
        let peer = self
            .peer
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotConnected, "no peer address"))?;
        socket.send_to(frame.bytes, peer).await?;
        Ok(())
    }

    async fn close(&mut self) -> io::Result<()> {
        // UdpSocket has no kernel-level "close" handshake; dropping
        // the socket releases the FD. Set our handle to None so
        // subsequent calls report NotConnected.
        self.socket = None;
        self.peer = None;
        Ok(())
    }

    async fn poll_event(&mut self) -> LinkEvent {
        let socket = match self.socket.as_ref() {
            Some(s) => s,
            None => {
                return LinkEvent::Lost {
                    cause: LostCause::PeerClosed,
                }
            }
        };
        // Single datagram size cap = 65507 bytes (max UDP payload).
        // R51 baseline allocates per-recv; production tuning will
        // use a recycled buffer pool (RFC §5.E lifecycle).
        let mut buf = vec![0u8; 65507];
        match socket.recv_from(&mut buf).await {
            Ok((n, src)) => {
                buf.truncate(n);
                // Carry the datagram source so a multicast consumer can
                // attribute Frame / KeepAlive / Close to a peer by address
                // (harmless for unicast, which ignores it).
                LinkEvent::Rx(RxFrame::with_src(buf, src))
            }
            Err(_) => LinkEvent::Lost {
                cause: LostCause::OsError,
            },
        }
    }
}

#[cfg(all(test, feature = "transport-link-tcp"))]
mod poll_framed_lowlatency_tests {
    use super::*;

    /// transport-lowlatency — a 4-byte u32 length prefix over `u16::MAX` is
    /// rejected (`Lost`) BEFORE allocation, mirroring zenoh's over-max batch
    /// rejection ("Batch len is invalid"). Guards the lowlatency rx path against
    /// a hostile peer forcing wz to allocate an attacker-chosen buffer (the u16
    /// path is inherently capped by its type; the u32 path is not).
    #[tokio::test]
    async fn lowlatency_rx_rejects_oversize_u32_prefix() {
        // u32 LE 0x0001_0000 = 65536 = u16::MAX + 1.
        let bytes = [0x00u8, 0x00, 0x01, 0x00];
        let mut src: &[u8] = &bytes;
        let mut st = ReadState::Idle;
        let ev = poll_framed(&mut st, &mut src, true).await;
        // R2288 — the CAUSE is asserted, not just the refusal. `Lost { .. }`
        // was what this test checked until the reachability gate derived that
        // nothing tied it to the `PeerClosed` the site actually returns: a
        // wildcard passes equally well if the site is changed to `OsError`, and
        // the two causes exist to be told apart by a caller.
        assert!(
            matches!(
                ev,
                LinkEvent::Lost {
                    cause: LostCause::PeerClosed
                }
            ),
            "an over-max lowlatency prefix is refused as PeerClosed, got {ev:?}"
        );
    }

    /// R2271 (open-debt item 577) — a zero-length batch is SKIPPED, and the
    /// frame behind it still arrives.
    ///
    /// The measured failure: a genuine zenohd on its abandon path writes a
    /// zero-length batch instead of the `0x3 Drop` marker, wz met it as
    /// `InboundParseError::Empty`, and the link went `LinkLost(PeerClosed)`.
    /// One harmless malformed batch from a peer ended the session.
    ///
    /// ⛔ THE SECOND FRAME IS THE ASSERTION, not the absence of a `Lost`. A fix
    /// that skipped the empty batch and then lost its place in the stream would
    /// satisfy "no Lost" perfectly well by hanging or by returning garbage; only
    /// reading the NEXT frame correctly says the state machine resynchronised.
    /// The two frames are handed over in one buffer for the same reason -- a
    /// second `poll_framed` over a fresh slice would not test that at all.
    ///
    /// ⛔ AND THE CONTROL IS IN THE SAME TEST: a batch that is malformed while
    /// NOT being empty must still be `Lost`. Without it this reads equally well
    /// as "the codec-error arm was deleted", which would be a much worse
    /// change than the one item 577 asked for.
    #[tokio::test]
    async fn a_zero_length_batch_is_skipped_and_the_next_frame_still_arrives() {
        let real = StreamEnvelope {
            payload_len: 3,
            payload: &[0x01, 0x02, 0x03],
        }
        .encode_to_vec();

        // An empty batch is the two prefix bytes and nothing else.
        let mut wire = vec![0x00u8, 0x00];
        wire.extend_from_slice(&real);
        let mut src: &[u8] = &wire;
        let mut st = ReadState::Idle;
        match poll_framed(&mut st, &mut src, false).await {
            LinkEvent::Rx(rx) => assert_eq!(rx.bytes, vec![0x01, 0x02, 0x03]),
            other => panic!("the empty batch must be skipped, not {other:?}"),
        }

        // ...and TWO of them in a row, because a fix that consumed one by
        // falling through would pass the leg above and fail here.
        let mut wire = vec![0x00u8, 0x00, 0x00, 0x00];
        wire.extend_from_slice(&real);
        let mut src: &[u8] = &wire;
        let mut st = ReadState::Idle;
        match poll_framed(&mut st, &mut src, false).await {
            LinkEvent::Rx(rx) => assert_eq!(rx.bytes, vec![0x01, 0x02, 0x03]),
            other => panic!("two empty batches must both be skipped, not {other:?}"),
        }

        // transport-lowlatency carries the same shape behind a 4-byte prefix,
        // and upstream tolerates it there too (`while reader.can_read()`).
        let mut wire = vec![0x00u8, 0x00, 0x00, 0x00];
        wire.extend_from_slice(&[0x02, 0x00, 0x00, 0x00, 0xAA, 0xBB]);
        let mut src: &[u8] = &wire;
        let mut st = ReadState::Idle;
        match poll_framed(&mut st, &mut src, true).await {
            LinkEvent::Rx(rx) => assert_eq!(rx.bytes, vec![0xAA, 0xBB]),
            other => panic!("an empty lowlatency batch must be skipped, not {other:?}"),
        }

        // THE CONTROL: a batch that ENDS EARLY is still fatal. Declared length
        // 3, one byte delivered, then EOF -> `Lost`. Without this the whole
        // test reads equally well as "the failure arms were deleted".
        //
        // ⚠ This is not the control that was written FIRST, and the difference
        // is a finding rather than a detail. The first attempt fed a "malformed
        // but non-empty" batch and expected the envelope decode to refuse it --
        // and it did not, because this call site always hands the codec
        // `2 + payload_len` bytes taken from those very two, so the two reads of
        // one number always agree. R2271 recorded the reason as "`decode` fails
        // on exactly one condition, fewer than two bytes remaining"; R2288
        // measured that and it is WRONG -- `decode` has four failure exits, and
        // on a SHORT frame it does not take any of them, it panics indexing
        // `raw[2..2 + payload_len]`. The conclusion R2271 drew from it survived
        // the correction: the arm had no path to being true. R2288 removed it
        // (item 610) and gave every surviving refusal a `REACHED-BY:` marker
        // plus the test named there. EOF is a reachable fatal case, so EOF is
        // the control here; the other four have tests of their own below.
        let wire = [0x03u8, 0x00, 0xAA];
        let mut src: &[u8] = &wire;
        let mut st = ReadState::Idle;
        let ev = poll_framed(&mut st, &mut src, false).await;
        assert!(
            matches!(ev, LinkEvent::Lost { .. }),
            "a truncated batch must still lose the link, got {ev:?}"
        );
    }

    /// R2288 (open-debt item 610) — a reader that always fails, so the two
    /// `Err(_) => Lost { OsError }` refusals in [`poll_framed`] have an input
    /// that reaches them.
    ///
    /// Both were unmeasured before this round for the same reason item 610's
    /// arm was: nothing in the suite could produce an IO error from a `&[u8]`,
    /// which is what every other test here reads from. They differ from the
    /// dead arm in the way that matters -- the OS really can fail a read
    /// mid-frame, so the path exists and only the INPUT was missing.
    /// `failing_after` distinguishes the prefix site from the payload site:
    /// bytes flow until that many have been handed over, then every read errors.
    struct FailingReader {
        bytes: Vec<u8>,
        cursor: usize,
        failing_after: usize,
    }

    impl tokio::io::AsyncRead for FailingReader {
        fn poll_read(
            mut self: std::pin::Pin<&mut Self>,
            _cx: &mut std::task::Context<'_>,
            buf: &mut tokio::io::ReadBuf<'_>,
        ) -> std::task::Poll<io::Result<()>> {
            if self.cursor >= self.failing_after {
                return std::task::Poll::Ready(Err(io::Error::other("injected read failure")));
            }
            let end = (self.cursor + buf.remaining())
                .min(self.failing_after)
                .min(self.bytes.len());
            let chunk = &self.bytes[self.cursor..end];
            buf.put_slice(chunk);
            self.cursor = end;
            std::task::Poll::Ready(Ok(()))
        }
    }

    /// R2288 (item 610) — the `Ok(0)` refusal while reading the LENGTH PREFIX.
    /// A peer that closes between frames delivers zero bytes at frame start.
    #[tokio::test]
    async fn a_stream_that_ends_before_the_prefix_loses_the_link() {
        let mut src: &[u8] = &[];
        let mut st = ReadState::Idle;
        let ev = poll_framed(&mut st, &mut src, false).await;
        assert!(
            matches!(
                ev,
                LinkEvent::Lost {
                    cause: LostCause::PeerClosed
                }
            ),
            "EOF at frame start is PeerClosed, got {ev:?}"
        );
        assert!(
            matches!(st, ReadState::Idle),
            "the state machine must reset so a retry inherits no partial buffer"
        );
    }

    /// R2288 (item 610) — the `Err(_)` refusal while reading the LENGTH PREFIX,
    /// which is `OsError` rather than `PeerClosed`: the distinction is the whole
    /// point of having two causes, and nothing measured it until this round.
    #[tokio::test]
    async fn an_io_error_reading_the_prefix_loses_the_link() {
        let mut src = FailingReader {
            bytes: vec![0x02, 0x00],
            cursor: 0,
            failing_after: 0,
        };
        let mut st = ReadState::Idle;
        let ev = poll_framed(&mut st, &mut src, false).await;
        assert!(
            matches!(
                ev,
                LinkEvent::Lost {
                    cause: LostCause::OsError
                }
            ),
            "a failed prefix read is OsError, not PeerClosed, got {ev:?}"
        );
    }

    /// R2288 (item 610) — the `Ok(0)` refusal MID-PAYLOAD. Distinct from the
    /// prefix site above: the length was accepted, the buffer allocated, and the
    /// peer then stopped short of filling it.
    #[tokio::test]
    async fn a_frame_truncated_mid_payload_loses_the_link() {
        // Declared 4 bytes of payload, two delivered, then EOF.
        let wire = [0x04u8, 0x00, 0xAA, 0xBB];
        let mut src: &[u8] = &wire;
        let mut st = ReadState::Idle;
        let ev = poll_framed(&mut st, &mut src, false).await;
        assert!(
            matches!(
                ev,
                LinkEvent::Lost {
                    cause: LostCause::PeerClosed
                }
            ),
            "a payload that ends early is PeerClosed, got {ev:?}"
        );
        assert!(
            matches!(st, ReadState::Idle),
            "a half-filled frame must not survive into the next read"
        );
    }

    /// R2288 (item 610) — the `Err(_)` refusal MID-PAYLOAD, the fifth and last
    /// way this function can refuse. `failing_after: 2` lets the whole prefix
    /// through and fails the read that would have filled the payload.
    #[tokio::test]
    async fn an_io_error_reading_the_payload_loses_the_link() {
        let mut src = FailingReader {
            bytes: vec![0x04, 0x00, 0xAA, 0xBB, 0xCC, 0xDD],
            cursor: 0,
            failing_after: 2,
        };
        let mut st = ReadState::Idle;
        let ev = poll_framed(&mut st, &mut src, false).await;
        assert!(
            matches!(
                ev,
                LinkEvent::Lost {
                    cause: LostCause::OsError
                }
            ),
            "a failed payload read is OsError, got {ev:?}"
        );
    }

    /// R2288 (open-debt item 610) — THE CONTRACT THAT REPLACES THE DEAD ARM.
    ///
    /// [`poll_framed`] no longer routes the completed 2-byte frame back through
    /// `StreamEnvelope::decode`, because that decode re-read a number this loop
    /// had just written and could not disagree with it. What the codec still
    /// owns is the shape ITSELF, on the write side -- so the binding that keeps
    /// the two halves in step is this: whatever `StreamEnvelope::encode_to_vec`
    /// emits, this reader must unframe back to the same payload.
    ///
    /// ⛔ THE ASSERTION IS THE ROUND TRIP, not the byte layout. Pinning
    /// `wire[0..2]` to a hand-written little-endian pair would pass even if the
    /// reader were changed to read big-endian, since the test would then be
    /// checking the codec against a literal instead of against the reader. Two
    /// payload lengths whose LE and BE encodings differ (`0x0102`) are what make
    /// an endianness flip on either side fail here.
    #[tokio::test]
    async fn the_writers_codec_frames_what_this_reader_unframes() {
        for payload in [
            vec![0xAAu8],
            vec![0x01, 0x02, 0x03],
            // 258 bytes: payload_len 0x0102, whose LE and BE encodings differ,
            // so a width or endianness change on either half is visible here.
            vec![0x5A; 258],
        ] {
            let wire = StreamEnvelope {
                payload_len: payload.len() as u16,
                payload: &payload,
            }
            .encode_to_vec();
            let mut src: &[u8] = &wire;
            let mut st = ReadState::Idle;
            match poll_framed(&mut st, &mut src, false).await {
                LinkEvent::Rx(rx) => assert_eq!(
                    rx.bytes, payload,
                    "the reader must unframe exactly what the codec framed"
                ),
                other => panic!("codec-framed wire must arrive as Rx, not {other:?}"),
            }
        }
    }
}

/// R311y832 — the three multicast knobs a UDP locator's `#`-config span can
/// carry, as one value rather than three parameters.
///
/// zenoh names them together in one module (`config::UDP_MULTICAST_IFACE` /
/// `_JOIN` / `_TTL`, `zenoh-link-udp/src/lib.rs:108-112`) and consumes them in
/// one function, so they travel together here too. The struct is also what
/// keeps the two constructors below from growing a fourth and fifth positional
/// argument — the R311y808 shape, where folding two parameters into one value
/// shortened the signature instead of lengthening it.
///
/// `Default` is the pre-R311y832 behaviour byte for byte: no interface pin, no
/// extra groups, and the OS hop limit.
#[derive(Debug, Default, Clone, Copy)]
#[cfg(any(
    feature = "scouting-active",
    feature = "scouting-responder",
    feature = "transport-multicast"
))]
pub struct McastSocketConfig<'a> {
    /// `#iface=<name-or-ip>` (R311y454): which interface's membership is
    /// installed and which one egress leaves by.
    pub iface: Option<&'a str>,
    /// `#ttl=<n>`: the multicast hop limit. `None` leaves the OS default, which
    /// is 1 — one subnet.
    pub ttl: Option<u32>,
    /// `#join=<group>` values, joined in addition to the locator's own group.
    pub extra_joins: &'a [String],
}

#[cfg(any(
    feature = "scouting-active",
    feature = "scouting-responder",
    feature = "transport-multicast"
))]
impl McastSocketConfig<'_> {
    /// Parse every `#join=` value into a v4 group address.
    ///
    /// Refused rather than skipped on a bad value, and refused BEFORE any
    /// membership is installed: a partially-joined receiver is subscribed to
    /// some of what it was told and silent about the rest, which is the shape
    /// that looks configured and is not. wz is v4-only on this path (the whole
    /// multicast surface is — `wz-ap-demo/src/runner.rs` says so of itself), so
    /// a v6 group here is a refusal with its own message rather than a mis-parse.
    ///
    /// R311y833 — gated on `transport-link-udp` as well as this impl's own
    /// `any(scouting-active, transport-multicast)`, because its ONE caller is
    /// `UdpDriver::bind_multicast_v4` and that whole impl block carries the udp
    /// gate (`:1801`). The union `wz-runtime-tokio-multicast-tests` forces —
    /// multicast ON, `transport-link-udp` OFF under `--no-default-features` —
    /// left this method compiled and uncalled, which Layer C1cf reads as dead
    /// code. R311y832 added the method with the impl's gate alone.
    #[cfg(feature = "transport-link-udp")]
    fn resolved_joins(&self) -> io::Result<Vec<std::net::Ipv4Addr>> {
        self.extra_joins
            .iter()
            .map(|g| {
                g.parse::<std::net::Ipv4Addr>().map_err(|_| {
                    io::Error::new(
                        io::ErrorKind::InvalidInput,
                        format!("#join={g} is not an IPv4 multicast group"),
                    )
                })
            })
            .collect()
    }
}

/// R311y832 — the owned form of [`McastSocketConfig`], for the seams that cross
/// a `tokio::spawn` and so cannot borrow. Same three keys, same meaning; the
/// borrowed view is taken back with [`as_socket_config`](Self::as_socket_config)
/// at the socket.
#[derive(Debug, Default, Clone)]
#[cfg(any(
    feature = "scouting-active",
    feature = "scouting-responder",
    feature = "transport-multicast"
))]
pub struct McastGroupOptions {
    /// `#iface=<name-or-ip>`.
    pub iface: Option<String>,
    /// `#ttl=<n>`.
    pub ttl: Option<u32>,
    /// `#join=<group>` values.
    pub joins: Vec<String>,
}

#[cfg(any(
    feature = "scouting-active",
    feature = "scouting-responder",
    feature = "transport-multicast"
))]
impl McastGroupOptions {
    /// Borrow this as the socket-facing config.
    pub fn as_socket_config(&self) -> McastSocketConfig<'_> {
        McastSocketConfig {
            iface: self.iface.as_deref(),
            ttl: self.ttl,
            extra_joins: &self.joins,
        }
    }
}

/// R311y832 — the UDP multicast locator config surface
/// (zenoh `zenoh-link-udp/src/lib.rs:108-112`: `iface` / `join` / `ttl`).
#[cfg(all(test, feature = "transport-multicast", feature = "transport-link-udp"))]
mod udp_multicast_config_tests {
    use super::*;

    /// A group and port nothing else on this host is expected to use, so two
    /// cases in one test binary do not collide on the membership.
    const GROUP: std::net::Ipv4Addr = std::net::Ipv4Addr::new(239, 255, 91, 32);

    #[tokio::test]
    async fn a_multicast_socket_leaves_the_local_subnet_only_when_asked() {
        // THE MEASUREMENT THIS ROUND STARTED FROM. A multicast datagram's reach
        // is its TTL, and the OS default is 1 — one subnet. zenoh exposes the
        // knob as the locator config key `ttl`
        // (`zenoh-link-udp/src/multicast.rs:355-374`, `set_multicast_ttl_v4` on
        // the sending socket); wz called `set_multicast_ttl_v4` NOWHERE, so no
        // wz deployment could reach past its own subnet by any route.
        let d = UdpDriver::bind_multicast_v4(GROUP, 0, McastSocketConfig::default())
            .await
            .expect("bind the group");
        let sock = d.socket.as_ref().expect("bound");
        assert_eq!(
            sock.multicast_ttl_v4().expect("read ttl"),
            1,
            "the default is the single-subnet one, which is why the knob has to exist"
        );

        let d = UdpDriver::bind_multicast_v4(
            GROUP,
            0,
            McastSocketConfig {
                ttl: Some(8),
                ..Default::default()
            },
        )
        .await
        .expect("bind the group with a ttl");
        let sock = d.socket.as_ref().expect("bound");
        assert_eq!(
            sock.multicast_ttl_v4().expect("read ttl"),
            8,
            "a requested ttl must reach the socket, or the config key is decoration"
        );
    }

    #[tokio::test]
    async fn the_send_only_half_carries_the_hop_limit_too() {
        // zenoh sets the TTL on its `ucast_sock` — the SENDING socket
        // (`multicast.rs:363`). wz splits the roles the same way for the router
        // egress, so a hop limit that only reached the bidirectional
        // constructor would leave the one path that exists to send unbounded by
        // it.
        let d = UdpDriver::bind_multicast_tx_v4(
            GROUP,
            7446,
            McastSocketConfig {
                ttl: Some(5),
                ..Default::default()
            },
        )
        .await
        .expect("bind a sender");
        let sock = d.socket.as_ref().expect("bound");
        assert_eq!(sock.multicast_ttl_v4().expect("read ttl"), 5);
    }

    #[tokio::test]
    async fn a_malformed_extra_join_installs_no_membership_at_all() {
        // The refusal is BEFORE the first join, so a typo in the second of two
        // groups does not leave the first installed and the caller believing it
        // has both.
        let joins = vec!["239.255.91.33".to_string(), "not-an-address".to_string()];
        // `expect_err` would need `UdpDriver: Debug`, which it is not.
        let e = match UdpDriver::bind_multicast_v4(
            GROUP,
            0,
            McastSocketConfig {
                extra_joins: &joins,
                ..Default::default()
            },
        )
        .await
        {
            Ok(_) => panic!("a malformed #join= was accepted"),
            Err(e) => e,
        };
        assert_eq!(e.kind(), std::io::ErrorKind::InvalidInput);
        assert!(
            e.to_string().contains("not-an-address"),
            "the message names the value: {e}"
        );
    }

    #[tokio::test]
    async fn an_extra_join_makes_a_second_group_readable_on_one_socket() {
        // THE POINT OF `join`, and the only assertion that distinguishes a real
        // membership from a stored string: send to the EXTRA group and read it
        // off the socket bound for the locator's own.
        const EXTRA: std::net::Ipv4Addr = std::net::Ipv4Addr::new(239, 255, 91, 33);
        let port = 47_446u16;
        let joins = vec![EXTRA.to_string()];
        let rx = UdpDriver::bind_multicast_v4(
            GROUP,
            port,
            McastSocketConfig {
                extra_joins: &joins,
                ..Default::default()
            },
        )
        .await
        .expect("bind with an extra join");

        let tx = UdpDriver::bind_multicast_tx_v4(EXTRA, port, McastSocketConfig::default())
            .await
            .expect("bind a sender");
        let sock = rx.socket.as_ref().expect("bound");
        tx.socket
            .as_ref()
            .expect("bound")
            .send_to(b"extra-group", SocketAddr::from((EXTRA, port)))
            .await
            .expect("send to the extra group");

        let mut buf = [0u8; 32];
        let n = tokio::time::timeout(std::time::Duration::from_secs(2), sock.recv(&mut buf))
            .await
            .expect("the extra group's datagram arrives within the budget")
            .expect("recv");
        assert_eq!(&buf[..n], b"extra-group");
    }
}
