/// R311y237 (§5.23 `adminspace-plugins-handlers`) — the wz-native plugin registry:
/// the compiled-in composable subsystems THIS binary carries, as
/// [`adminspace::AdminPlugin`] entries the admin `plugins/**` + `status/plugins/**`
/// legs (+ the local_data `plugins` field) reply from. wz has NO dlopen
/// plugin-manager (the §5.22 plugin family is reserved) — a wz "plugin" is a
/// cargo-feature/subsystem with a zenoh-plugin analogue, so the registry is built
/// from `cfg!(feature = ..)`, NOT enumerated off a `PluginsManager`. Reported state
/// is `Loaded` (compiled into the binary); a host that actually instantiates the
/// subsystem at runtime would report `Started` (which additionally surfaces it in
/// the local_data `plugins` field, faithful to zenoh's `started_plugins_iter`).
/// `version` is the node build version. Currently reports `storage_manager` (the wz
/// mirror of `zenoh-plugin-storage-manager`) under `storage-backend`; `rest`
/// (`zenoh-plugin-rest`, under `rest-http-bridge`) is an extension point.
#[cfg(feature = "adminspace-plugins-handlers")]
pub fn compiled_plugins(version: &str) -> Vec<wz_session_core::adminspace::AdminPlugin> {
    // Each compiled-in subsystem with a zenoh-plugin analogue contributes one entry;
    // an empty registry (the surface compiled but no subsystem) is valid. Built
    // branch-wise so `unused_mut` / unused-param lints stay clean across the
    // storage-backend toggle (a `let mut` with all pushes cfg'd out is a hard error
    // under `-D warnings`). Extending with `rest` (under `rest-http-bridge`) appends
    // another cfg branch here.
    #[cfg(feature = "storage-backend")]
    {
        use wz_session_core::adminspace::{AdminPlugin, AdminPluginState};
        vec![AdminPlugin::wz_static(
            "storage_manager",
            "storage_manager",
            Some(version),
            AdminPluginState::Loaded,
        )]
    }
    #[cfg(not(feature = "storage-backend"))]
    {
        let _ = version;
        Vec::new()
    }
}

/// R311y239 (`adminspace-config-hotreload`) — the DYNAMIC plugin-registry BUILDER:
/// the config-hotreload counterpart of [`compiled_plugins`], reporting `storage_manager`
/// as `Started` when a storage is LIVE (`storage_started`, i.e.
/// `RuntimeStorageManager::is_empty() == false`) and `Loaded` otherwise. The
/// [`crate::adminspace::answer_admin_query`] SEAM already replies whatever
/// `&[AdminPlugin]` slice its caller passes, so a host that OWNS a storage manager
/// builds its slice with THIS (feeding its live state) and a `storage-add` then flips
/// `storage_manager` Loaded→Started in the y237 plugins admin surface (local_data
/// `plugins` object + the Started-only `status/plugins` legs).
///
/// WIRING STATUS: WIRED. The `--storage-host` demo mode (`runner.rs`
/// `run_storage_host`) owns a `RuntimeStorageManager` and builds its admin slice with
/// THIS, feeding `!manager.is_empty()`; Layer E6h drives the resulting Loaded ->
/// Started -> Loaded flip with a foreign zenoh-pico client. The library Session host
/// (`session/mod.rs`) and the routing-peer / router-hat demo hosts hold no storage
/// manager, so they still — correctly — pass the STATIC [`compiled_plugins`] slice.
///
/// (This note said "no SHIPPING admin host calls this yet" long after the storage
/// host landed. R311y828 corrected it while wiring the status sub-tree through the
/// same host; a stale "not wired" note reopens finished work exactly as the
/// `Volume::create_storage` one did.)
#[cfg(feature = "adminspace-config-hotreload")]
pub fn compiled_plugins_dyn(
    version: &str,
    storage_started: bool,
) -> Vec<wz_session_core::adminspace::AdminPlugin> {
    #[cfg(feature = "storage-backend")]
    {
        use wz_session_core::adminspace::{AdminPlugin, AdminPluginState};
        let state = if storage_started {
            AdminPluginState::Started
        } else {
            AdminPluginState::Loaded
        };
        vec![AdminPlugin::wz_static(
            "storage_manager",
            "storage_manager",
            Some(version),
            state,
        )]
    }
    #[cfg(not(feature = "storage-backend"))]
    {
        let _ = (version, storage_started);
        Vec::new()
    }
}

