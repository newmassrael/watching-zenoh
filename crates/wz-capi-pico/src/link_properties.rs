//! What pico's link of a kind reports about itself: its MTU, whether it is a stream, and
//! whether it is reliable.
//!
//! Two planes report links in pico's words, the connectivity plane (`z_link_mtu`,
//! `z_link_is_streamed`, `z_link_is_reliable`) and the admin space's link document, and
//! the two are separate switches (`Z_FEATURE_CONNECTIVITY`, `Z_FEATURE_ADMIN_SPACE`), so
//! the table lives here rather than in either.

use wz_session_core::link::LinkKind;

// The table is the SCE `algorithm` document `sources/algorithms/pico_link_properties.scxml` and
// the record it returns, `pico_link_reported.scxml`, committed at `out/wz-capi-pico/` and
// `include!`-ed from there as sibling modules (regenerated by `scripts/regen-codegen.sh`).
mod generated {
    #[allow(dead_code)]
    pub(super) mod pico_link_reported {
        include!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../out/wz-capi-pico",
            "/pico_link_reported.rs"
        ));
    }
    pub(super) mod pico_link_properties {
        include!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../out/wz-capi-pico",
            "/pico_link_properties.rs"
        ));
    }
}

/// The number `pico_link_properties.scxml` names a link by: the pico link that stands for a
/// kind wz has, 0 for a link whose kind the driver cannot name, and [`NO_PICO_LINK`] for a kind
/// pico has no link for. Wildcard-free, so a new kind must say which it is.
fn pico_link_code(kind: Option<LinkKind>) -> u8 {
    match kind {
        None => 0,
        Some(LinkKind::Tcp) => 1,
        Some(LinkKind::Tls) => 2,
        Some(LinkKind::Udp) => 3,
        Some(LinkKind::Ws) => 4,
        Some(LinkKind::Serial) => 5,
        Some(
            LinkKind::UdpReliable
            | LinkKind::Quic
            | LinkKind::QuicDatagram
            | LinkKind::Unixpipe
            | LinkKind::UnixsockStream
            | LinkKind::Vsock,
        ) => NO_PICO_LINK,
    }
}

/// The number of a kind pico has no link for: any the document does not name.
const NO_PICO_LINK: u8 = 0xff;

/// `(mtu, is_streamed, is_reliable)` of a link, as pico's link of that kind
/// answers.
///
/// pico's five links fix all three per TYPE (`_z_get_link_mtu_tcp` and its
/// siblings, and `zl->_cap._flow` / `zl->_cap._is_reliable` beside them). A kind
/// pico has no link for keeps what the registry reports. A link whose kind the
/// driver cannot name reports pico's own zeros, which is what pico answers for a
/// transport with no link object at all
/// (`vendor/zenoh-pico/include/zenoh-pico/api/primitives.h` @
/// `static inline void _z_transport_link_properties_from_transport(`).
/// The values per kind are `sources/algorithms/pico_link_properties.scxml`.
pub(crate) fn pico_link_properties(kind: Option<LinkKind>, reported_mtu: u16) -> (u16, bool, bool) {
    let streamed = kind.is_some_and(|kind| kind.is_streamed());
    let reliable = kind.is_some_and(|kind| kind.is_reliable());
    let reported = generated::pico_link_properties::pico_link_properties(
        pico_link_code(kind),
        reported_mtu,
        streamed,
        reliable,
    );
    (reported.mtu, reported.streamed, reported.reliable)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The link a face reports follows pico's table for the kinds pico has and
    /// the registry's answer for the rest.
    ///
    /// # Control
    ///
    /// Reporting the negotiated MTU for TCP (2048 from a pico peer) where pico's
    /// link says 65535 reds the first row.
    #[test]
    fn a_link_reports_what_pico_reports_for_its_kind() {
        let reported = 777;
        let table = [
            (Some(LinkKind::Tcp), (65535, true, true)),
            (Some(LinkKind::Tls), (65535, true, true)),
            (Some(LinkKind::Udp), (1450, false, false)),
            (Some(LinkKind::Ws), (65535, false, true)),
            (Some(LinkKind::Serial), (1500, false, false)),
            (None, (0, false, false)),
            // pico has no such link: the registry's answers stand.
            (Some(LinkKind::Quic), (reported, true, true)),
            (Some(LinkKind::QuicDatagram), (reported, false, false)),
            (Some(LinkKind::UdpReliable), (reported, true, true)),
            (Some(LinkKind::Unixpipe), (reported, true, true)),
        ];
        for (kind, want) in table {
            assert_eq!(pico_link_properties(kind, reported), want, "{kind:?}");
        }
        // Every kind the registry can report has a row above or an arm there;
        // this is the population, derived from the enum.
        for kind in LinkKind::ALL {
            let _ = pico_link_properties(Some(*kind), reported);
        }
    }

    /// Every kind pico has no link for, of the whole population, keeps the registry's three
    /// answers, and every kind pico has a link for is named by a number of its own.
    ///
    /// # Control
    ///
    /// Naming Vsock as pico's serial link (5) reds the first assertion; giving two pico links one
    /// number reds the second.
    #[test]
    fn a_kind_pico_has_no_link_for_keeps_the_registrys_answers() {
        let reported = 4321;
        let mut named = std::vec::Vec::new();
        for &kind in LinkKind::ALL {
            let code = pico_link_code(Some(kind));
            if code == NO_PICO_LINK {
                assert_eq!(
                    pico_link_properties(Some(kind), reported),
                    (reported, kind.is_streamed(), kind.is_reliable()),
                    "{kind:?}"
                );
            } else {
                assert!(!named.contains(&code), "{kind:?} shares {code}");
                named.push(code);
            }
        }
        assert_eq!(
            named.len(),
            5,
            "pico's five links: tcp, tls, udp, ws, serial"
        );
        assert_eq!(pico_link_code(None), 0);
    }
}
