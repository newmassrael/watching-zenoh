//! What a fuzzing run does to a payload.
//!
//! Moved from `wz-replay` (R311y700), which re-exports [`Mutation`] and [`MutationOutcome`] at the
//! paths they had; the C ABI over it (`wz-capi-replay`) and every caller see the same bytes. The
//! definitions are the contract, and the byte vectors in this module's tests hold them: a bit index
//! counts from the low bit of byte 0, a truncation keeps the first bytes, and the generated bytes
//! are the low byte of each SplitMix64 output from the seed, in order.

#[cfg(feature = "alloc")]
use alloc::vec::Vec;

/// R311y700 — what a fuzzing run does to a payload.
///
/// # Why the mutations are named and seeded rather than random
///
/// A fuzzing run that cannot be repeated is a bug report nobody can act on. So every mutation here
/// is a pure function of the payload and the parameters, and the seeded one is a named generator
/// rather than the thread's entropy. A reader who sees a peer fall over reruns the same command and
/// gets the same bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mutation {
    /// Send it as captured.
    None,
    /// Flip one bit. `at` is a BIT index (bit `at % 8`, from the low bit, of byte `at / 8`); a
    /// payload shorter than that is left alone rather than extended, and [`MutationOutcome`] says
    /// so.
    FlipBit { at: usize },
    /// Keep the first `to` bytes. Longer payloads are cut; shorter ones are left alone.
    Truncate { to: usize },
    /// Append `count` bytes derived from the seed, which is how a length field that is not checked
    /// gets found.
    Extend { count: usize, seed: u64 },
    /// Rewrite every byte from a seeded generator, keeping the length. The blunt one, and the one
    /// that finds a parser that trusts its input.
    Scramble { seed: u64 },
}

/// What a mutation did, so a replay can report it rather than only perform it.
#[cfg(feature = "alloc")]
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MutationOutcome {
    /// The bytes to send.
    pub payload: Vec<u8>,
    /// Whether the payload actually changed. `false` for [`Mutation::None`] and for a mutation
    /// whose target was outside this payload; the second is the case a caller must be able to
    /// see, because a fuzzing run that silently changed nothing looks exactly like one that found
    /// nothing.
    pub changed: bool,
}

/// SplitMix64, the one generator of this crate: each call advances `state` by the golden-ratio
/// increment and returns the mixed word. Chosen because its constants are in its own definition
/// rather than remembered from a table; the published sequence from state 0 holds it in this
/// module's tests.
pub fn splitmix64(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// What [`Mutation::apply_into`] wrote: how many bytes, and whether they differ from the body.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Applied {
    /// The length of the mutated payload at the start of the buffer.
    pub len: usize,
    /// Whether the payload changed (see [`Mutation`]).
    pub changed: bool,
}

impl Mutation {
    /// How long the mutated payload of a `body_len`-byte body is: the buffer [`Self::apply_into`]
    /// needs, which an interpreter with no allocator sizes its storage by. `const`, so an image
    /// sizes that storage when it is built.
    pub const fn output_len(&self, body_len: usize) -> usize {
        match *self {
            // `min` is not `const`.
            Self::Truncate { to } if to < body_len => to,
            Self::Truncate { .. } => body_len,
            Self::Extend { count, .. } => body_len.saturating_add(count),
            _ => body_len,
        }
    }

    /// Apply this mutation to `body`, writing the payload to send at the start of `out`: the one
    /// definition, which [`Self::apply`] is built on. `None` when `out` is shorter than
    /// [`Self::output_len`], with nothing written that a caller may read.
    pub fn apply_into(&self, body: &[u8], out: &mut [u8]) -> Option<Applied> {
        let len = self.output_len(body.len());
        if out.len() < len {
            return None;
        }
        let kept = body.len().min(len);
        out[..kept].copy_from_slice(&body[..kept]);
        let changed = match *self {
            Self::None => false,
            Self::FlipBit { at } => match out[..len].get_mut(at / 8) {
                None => false,
                Some(slot) => {
                    *slot ^= 1u8 << (at % 8);
                    true
                }
            },
            Self::Truncate { to } => to < body.len(),
            Self::Extend { count, seed } => {
                let mut state = seed;
                for slot in &mut out[body.len()..len] {
                    *slot = splitmix64(&mut state) as u8;
                }
                count > 0
            }
            Self::Scramble { seed } => {
                let mut state = seed;
                for slot in &mut out[..len] {
                    *slot = splitmix64(&mut state) as u8;
                }
                out[..len] != *body
            }
        };
        Some(Applied { len, changed })
    }

    /// Apply this mutation, into a payload of its own.
    #[cfg(feature = "alloc")]
    pub fn apply(&self, payload: &[u8]) -> MutationOutcome {
        let mut out = alloc::vec![0u8; self.output_len(payload.len())];
        let applied = self.apply_into(payload, &mut out).unwrap_or(Applied {
            len: 0,
            changed: false,
        });
        out.truncate(applied.len);
        MutationOutcome {
            payload: out,
            changed: applied.changed,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The published SplitMix64 sequence from state 0, which this generator must reproduce: the
    /// independent check under the byte vectors below.
    #[test]
    fn the_generator_is_splitmix64() {
        let mut state = 0u64;
        let words: [u64; 3] = core::array::from_fn(|_| splitmix64(&mut state));
        assert_eq!(
            words,
            [
                0xe220_a839_7b1d_cdaf,
                0x6e78_9e6a_a1b9_65f4,
                0x06c4_5d18_8009_454f
            ]
        );
    }

    /// The definitions as bytes, which a second implementation of this contract is held to.
    /// `m` applied to `body` with no allocator, into a buffer of 64: the bytes and the flag.
    fn into(m: Mutation, body: &[u8]) -> ([u8; 64], usize, bool) {
        let mut out = [0u8; 64];
        let applied = m
            .apply_into(body, &mut out)
            .expect("64 bytes hold every case here");
        (out, applied.len, applied.changed)
    }

    /// The definitions as bytes, which a second implementation of this contract is held to.
    #[test]
    fn the_mutations_are_these_bytes() {
        let (out, len, changed) = into(Mutation::FlipBit { at: 0 }, b"beta");
        assert_eq!((&out[..len], changed), (&b"ceta"[..], true));
        let (out, len, _) = into(Mutation::FlipBit { at: 15 }, b"beta");
        assert_eq!(&out[..len], [b'b', b'e' ^ 0x80, b't', b'a']);
        let (out, len, changed) = into(Mutation::FlipBit { at: 32 }, b"beta");
        assert_eq!((&out[..len], changed), (&b"beta"[..], false));
        let (out, len, changed) = into(Mutation::Truncate { to: 2 }, b"beta");
        assert_eq!((&out[..len], changed), (&b"be"[..], true));
        assert!(!into(Mutation::Truncate { to: 4 }, b"beta").2);
        let (out, len, _) = into(Mutation::Extend { count: 3, seed: 0 }, b"ab");
        assert_eq!(&out[..len], [b'a', b'b', 0xaf, 0xf4, 0x4f]);
        let (out, len, changed) = into(Mutation::Scramble { seed: 0 }, b"abcd");
        assert_eq!(
            (len, &out[..3], changed),
            (4, &[0xaf, 0xf4, 0x4f][..], true)
        );
        assert!(!into(Mutation::Scramble { seed: 0 }, &out[..4]).2);
        assert!(!into(Mutation::Scramble { seed: 9 }, b"").2);
        assert!(!into(Mutation::None, b"x").2);
        assert!(!into(Mutation::Extend { count: 0, seed: 1 }, b"x").2);
    }

    /// A buffer shorter than the mutated payload is refused, and the length it needs is stated.
    #[test]
    fn a_buffer_too_short_is_refused_and_its_need_stated() {
        let extend = Mutation::Extend { count: 3, seed: 0 };
        assert_eq!(extend.output_len(2), 5);
        assert_eq!(extend.apply_into(b"ab", &mut [0u8; 4]), None);
        assert_eq!(
            extend.apply_into(b"ab", &mut [0u8; 5]),
            Some(Applied {
                len: 5,
                changed: true
            })
        );
        assert_eq!(Mutation::Truncate { to: 1 }.output_len(4), 1);
    }

    /// The allocating form is the same definition: its bytes are `apply_into`'s for every case.
    #[cfg(feature = "alloc")]
    #[test]
    fn the_allocating_form_gives_the_same_bytes() {
        let cases = [
            Mutation::None,
            Mutation::FlipBit { at: 3 },
            Mutation::FlipBit { at: 99 },
            Mutation::Truncate { to: 1 },
            Mutation::Extend { count: 5, seed: 7 },
            Mutation::Scramble { seed: 7 },
        ];
        for m in cases {
            let (out, len, changed) = into(m, b"payload");
            let owned = m.apply(b"payload");
            assert_eq!(
                (owned.payload.as_slice(), owned.changed),
                (&out[..len], changed),
                "{m:?}"
            );
        }
    }
}
