#[test]
fn a_map_entry_is_a_map_only_on_a_repeated_field_with_a_key_a_map_may_have() {
    let entry = |key_type: i64| {
        message(
            "VEntry",
            &[
                field("key", 1, OPTIONAL, key_type, None),
                field("value", 2, OPTIONAL, STRING, None),
            ],
            &[],
            true,
        )
    };
    let holder = |label: i64, key_type: i64| {
        set(&[file(
            "a.proto",
            &[],
            &[message(
                "M",
                &[field("v", 1, label, MESSAGE, Some(".p.M.VEntry"))],
                &[entry(key_type)],
                false,
            )],
            &[],
        )])
    };
    let schema = SchemaSet::from_descriptor_set(&holder(REPEATED, INT32)).expect("a map reads");
    assert_eq!(
        schema.linked_messages().len(),
        1,
        "the entry is not a message of the schema"
    );
    assert_eq!(
        row(&schema.linked_messages()[0].fields[0]),
        "v 1 Map { key: Int32, value: Scalar(String) } Implicit None []"
    );
    let why = refusal(&holder(OPTIONAL, INT32));
    assert!(
        why.reason.contains("holds a map entry and is not repeated"),
        "{why}"
    );
    // A double may not key a map.
    let why = refusal(&holder(REPEATED, 1));
    assert!(
        why.reason
            .contains("has a key that is not an integral type"),
        "{why}"
    );
}

/// The payload of a message of the compiled schema, set, written, read back and refused, with no
/// `.proto` text read: the path a device build takes.
#[cfg(feature = "message-payload")]
#[test]
fn a_payload_is_written_and_read_by_the_compiled_schema() {
    use crate::message_payload::{Given, Got, Payload, Refusal, Wanted};

    let schema = compiled();
    let reading = schema
        .message("wz.fixture.Reading")
        .expect("the message is in the set");
    let mut p = Payload::new(&schema, reading);
    p.set("zone", Given::Unsigned(3)).expect("zone is set");
    p.set("label", Given::Text("a")).expect("label is set");
    assert_eq!(
        p.encode().expect("the payload encodes"),
        [0x08, 0x03, 0x1a, 0x01, b'a'],
        "zone and label in field order, laid by hand"
    );
    assert_eq!(p.get("label", Wanted::Text), Ok(Got::Text("a")));
    assert!(
        matches!(
            p.set("nowhere", Given::Signed(1)),
            Err(Refusal::Path { .. })
        ),
        "a path the schema has not is refused"
    );
    assert!(
        matches!(p.set("label", Given::Signed(1)), Err(Refusal::Type { .. })),
        "an integer into a string field is refused"
    );
}
