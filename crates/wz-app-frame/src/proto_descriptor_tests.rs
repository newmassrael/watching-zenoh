/// One line per field: what the typed reader and the writer read of it.
fn row(field: &Fld) -> String {
    let options: Vec<String> = field
        .options
        .iter()
        .map(|o| format!("{}={:?}", o.name, o.value))
        .collect();
    format!(
        "{} {} {:?} {:?} {:?} [{}]",
        field.name,
        field.number,
        field.kind,
        field.label,
        field.oneof,
        options.join(", ")
    )
}

fn named(options: &[FieldOption]) -> Vec<String> {
    options
        .iter()
        .map(|o| format!("{}={:?}", o.name, o.value))
        .collect()
}

