/// The compiled schema and the schema the text reader links from the same files are one table
/// for one table, index for index, with every option either reader carries.
#[cfg(feature = "proto-text")]
#[test]
fn the_text_and_the_compiled_descriptor_read_the_same_schema() {
    use crate::proto_schema::ProtoFile;

    let files = [
        ("google/protobuf/descriptor.proto", DESCRIPTOR_PROTO),
        ("nanopb.proto", NANOPB_PROTO),
        ("wz/common.proto", COMMON_PROTO),
        ("wz/fixture.proto", FIXTURE_PROTO),
    ]
    .map(|(name, text)| ProtoFile {
        name,
        text: text.as_bytes(),
    });
    let text = SchemaSet::read(&files).expect("the fixture's text reads");
    let compiled = compiled();

    let (ours, theirs) = (text.linked_messages(), compiled.linked_messages());
    assert_eq!(ours.len(), theirs.len(), "as many messages");
    for (a, b) in ours.iter().zip(theirs) {
        let at = &a.full_name;
        assert_eq!(a.full_name, b.full_name);
        assert_eq!(a.file, b.file, "{at}: the file");
        assert_eq!(a.parent, b.parent, "{at}: the message it is written in");
        assert_eq!(a.syntax, b.syntax, "{at}: the syntax");
        assert_eq!(a.oneofs, b.oneofs, "{at}: the oneofs");
        assert_eq!(named(&a.options), named(&b.options), "{at}: its options");
        let rows = |m: &crate::proto_types::Msg| m.fields.iter().map(row).collect::<Vec<_>>();
        assert_eq!(rows(a), rows(b), "{at}: the fields");
    }
    let (ours, theirs) = (text.linked_enums(), compiled.linked_enums());
    assert_eq!(ours.len(), theirs.len(), "as many enums");
    for (a, b) in ours.iter().zip(theirs) {
        assert_eq!(a.full_name, b.full_name);
        assert_eq!(a.syntax, b.syntax, "{}: the syntax", a.full_name);
        assert_eq!(a.values, b.values, "{}: the values", a.full_name);
    }
    for file in 0..files.len() {
        assert_eq!(
            named(text.options_of_file(file)),
            named(compiled.options_of_file(file)),
            "the options of file {file}"
        );
    }
}

// ---- descriptor sets laid by hand -------------------------------------------------------------

fn varint(out: &mut Vec<u8>, mut value: u64) {
    loop {
        let low = (value & 0x7f) as u8;
        value >>= 7;
        if value == 0 {
            out.push(low);
            return;
        }
        out.push(low | 0x80);
    }
}

fn int_field(out: &mut Vec<u8>, number: u64, value: i64) {
    varint(out, number << 3);
    // A negative int32 is written as its 64-bit two's complement, as protobuf writes it.
    varint(out, value as u64);
}

fn len_field(out: &mut Vec<u8>, number: u64, bytes: &[u8]) {
    varint(out, (number << 3) | 2);
    varint(out, bytes.len() as u64);
    out.extend_from_slice(bytes);
}

/// A `FieldDescriptorProto`: name, number, label, type and, for a message or an enum, its type
/// name.
fn field(name: &str, number: i64, label: i64, ty: i64, type_name: Option<&str>) -> Vec<u8> {
    let mut out = Vec::new();
    len_field(&mut out, 1, name.as_bytes());
    int_field(&mut out, 3, number);
    int_field(&mut out, 4, label);
    int_field(&mut out, 5, ty);
    if let Some(type_name) = type_name {
        len_field(&mut out, 6, type_name.as_bytes());
    }
    out
}

/// A `DescriptorProto` of its fields and nested messages; a map entry when `entry`.
fn message(name: &str, fields: &[Vec<u8>], nested: &[Vec<u8>], entry: bool) -> Vec<u8> {
    let mut out = Vec::new();
    len_field(&mut out, 1, name.as_bytes());
    for f in fields {
        len_field(&mut out, 2, f);
    }
    for n in nested {
        len_field(&mut out, 3, n);
    }
    if entry {
        len_field(&mut out, 7, &[0x38, 0x01]);
    }
    out
}

/// A `FileDescriptorProto` of package `p`, with what `more` adds after its messages.
fn file(name: &str, imports: &[&str], messages: &[Vec<u8>], more: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    len_field(&mut out, 1, name.as_bytes());
    len_field(&mut out, 2, b"p");
    for import in imports {
        len_field(&mut out, 3, import.as_bytes());
    }
    for m in messages {
        len_field(&mut out, 4, m);
    }
    out.extend_from_slice(more);
    out
}

fn set(files: &[Vec<u8>]) -> Vec<u8> {
    let mut out = Vec::new();
    for f in files {
        len_field(&mut out, 1, f);
    }
    out
}

const OPTIONAL: i64 = 1;
const REPEATED: i64 = 3;
const INT32: i64 = 5;
const STRING: i64 = 9;
const MESSAGE: i64 = 11;

/// One file `a.proto` holding the message `p.M` of `fields`.
fn one_message(fields: &[Vec<u8>]) -> Vec<u8> {
    set(&[file(
        "a.proto",
        &[],
        &[message("M", fields, &[], false)],
        &[],
    )])
}

fn refusal(bytes: &[u8]) -> ProtoDiagnostic {
    SchemaSet::from_descriptor_set(bytes).expect_err("the descriptor set is refused")
}

