//! Whether a reply of a replay reaches the receiving judge.
//!
//! A subscriber that asks a publisher for the frames it last sent gets them as replies, oldest
//! first, and they enter the receive path of its live samples: the same
//! [`crate::e2e_receiver::Receiver`] judges both. Some of them it has judged already, live or in
//! an earlier answer, and judging one again would read as a repetition, or an old one as a counter
//! that went backwards. So before a reply is judged, where its counter stands against the baseline
//! of the stream it would be judged in decides:
//!
//! * [`Admission::Duplicate`] - it carries the baseline's counter and the same CRC (its low 32
//!   bits): the very frame the judge holds. Dropped, nothing moves.
//! * [`Admission::Stale`] - it is behind the baseline by less than the ring's depth: a frame of
//!   the ring the judge has passed. Dropped, nothing moves.
//! * [`Admission::Judge`] - anything else, and judged: a frame ahead of the baseline; one as far
//!   behind as a whole ring or more, which is a publisher that started again; one carrying the
//!   baseline's counter with another CRC, which the judge reports as the repetition it is; a
//!   frame that is not intact, which the judge reports as such; and any reply of a stream with no
//!   baseline yet.
//!
//! The classification is an SCE algorithm document (`sources/algorithms/replay_reply_admission.scxml`),
//! generated into `out/wz-app-frame/`, so the wrapping arithmetic is the generator's. Live samples
//! are never admitted this way: a live sample is always judged.

use crate::e2e_receiver::Receiver;

// Regenerated by `scripts/regen-codegen.sh` from `sources/algorithms/`.
mod generated {
    include!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../out/wz-app-frame",
        "/replay_reply_admission.rs"
    ));
}

/// What `replay_reply_admission` answers for a duplicate.
const DUPLICATE: u8 = 1;
/// What it answers for a stale reply.
const STALE: u8 = 2;

/// What becomes of a reply.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Admission {
    /// Judge it, as a live sample is judged.
    Judge,
    /// The frame the judge holds as its baseline: drop it.
    Duplicate,
    /// A frame of the ring the judge has passed: drop it.
    Stale,
}

/// Where a reply stands against the baseline of the stream it would be judged in, read by
/// [`Receiver`] without judging it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Standing {
    /// The reply's counter.
    pub(crate) counter: u64,
    /// The reply's CRC, as the frame carries it.
    pub(crate) crc: u64,
    /// The stream's baseline.
    pub(crate) baseline: u64,
    /// The CRC of the frame that became the baseline.
    pub(crate) baseline_crc: Option<u64>,
    /// The counter field's width, as its all-ones value.
    pub(crate) mask: u64,
}

/// Whether two CRCs are equal in their low 32 bits: what a duplicate is judged by, whatever the
/// CRC's width.
fn same_low_32(a: u64, b: u64) -> bool {
    (a & 0xFFFF_FFFF) == (b & 0xFFFF_FFFF)
}

/// The admission of a reply carrying `counter`, against a stream whose baseline is `baseline`
/// (the counter field's width given as its all-ones `mask`), from a ring `depth` frames deep;
/// `same_crc` is whether the reply's CRC equals the baseline frame's in its low 32 bits.
pub fn classify(counter: u64, baseline: u64, mask: u64, depth: u64, same_crc: bool) -> Admission {
    match generated::replay_reply_admission(counter, baseline, mask, depth, same_crc) {
        DUPLICATE => Admission::Duplicate,
        STALE => Admission::Stale,
        _ => Admission::Judge,
    }
}

/// The admission of `frame`, a reply arriving on `stream` of `receiver`, from a ring `depth`
/// frames deep. It moves nothing in the receiver.
pub fn admit(receiver: &Receiver, stream: usize, frame: &[u8], depth: usize) -> Admission {
    let Some(standing) = receiver.standing(stream, frame) else {
        return Admission::Judge;
    };
    let same_crc = standing
        .baseline_crc
        .is_some_and(|held| same_low_32(held, standing.crc));
    classify(
        standing.counter,
        standing.baseline,
        standing.mask,
        depth as u64,
        same_crc,
    )
}

#[cfg(test)]
mod tests {
    use alloc::vec::Vec;

    use super::*;
    use crate::e2e_frame::{build, Values};
    use crate::e2e_profile::Profile;
    use crate::e2e_receiver::{Keying, Status};

    /// A 32-bit CRC first on the wire, a two-byte counter and a length: synthetic.
    const PROFILE: &str = r#"{
      "name": "replay-syn",
      "fields": [
        {"name": "crc", "bytes": 4},
        {"name": "counter", "bytes": 2},
        {"name": "length", "bytes": 2}
      ],
      "crc": {"field": "crc", "width": 32, "poly": "0x1EDC6F41", "init": "0xFFFFFFFF",
              "refin": true, "refout": true, "xorout": "0xFFFFFFFF",
              "cover": ["counter", "length", "@payload"]},
      "length": {"field": "length", "counts": "frame"},
      "counter": {"field": "counter", "max_gap": 3, "timeout_ms": 1000}
    }"#;

    const DEPTH: usize = 4;

    fn frame(counter: u64, payload: &[u8]) -> Vec<u8> {
        let profile = Profile::parse(PROFILE).expect("valid");
        build(&profile, &Values::new().whole("counter", counter), payload)
            .expect("builds")
            .bytes
    }

    fn receiver() -> Receiver {
        let profile = Profile::parse(PROFILE).expect("valid");
        Receiver::new(
            profile,
            &Values::new(),
            Keying::Indexed { streams: 2 },
            None,
            0,
        )
        .expect("made")
    }

    #[test]
    fn the_classification_is_the_document_s_three_answers() {
        let mask = 0xFFFF;
        assert_eq!(classify(10, 10, mask, 4, true), Admission::Duplicate);
        assert_eq!(classify(10, 10, mask, 4, false), Admission::Judge);
        assert_eq!(classify(9, 10, mask, 4, true), Admission::Stale);
        assert_eq!(classify(7, 10, mask, 4, false), Admission::Stale);
        assert_eq!(
            classify(6, 10, mask, 4, false),
            Admission::Judge,
            "a whole ring behind"
        );
        assert_eq!(classify(11, 10, mask, 4, false), Admission::Judge, "ahead");
        assert_eq!(
            classify(0xFFFF, 1, mask, 4, false),
            Admission::Stale,
            "two behind across the wrap of the counter's width"
        );
        assert_eq!(
            classify(0x1_0009, 10, mask, 4, false),
            Admission::Stale,
            "bits above the width are not the counter's"
        );
        assert_eq!(
            classify(9, 10, u64::MAX, 1, false),
            Admission::Judge,
            "a ring of one frame has nothing stale"
        );
    }

    #[test]
    fn a_duplicate_is_told_by_the_low_32_bits_of_the_crc() {
        assert!(same_low_32(0x1234_5678_9ABC_DEF0, 0x0000_0000_9ABC_DEF0));
        assert!(!same_low_32(0x9ABC_DEF0, 0x9ABC_DEF1));
    }

    #[test]
    fn a_stream_with_no_baseline_judges_every_reply() {
        let receiver = receiver();
        assert_eq!(
            admit(&receiver, 0, &frame(3, b"p"), DEPTH),
            Admission::Judge
        );
        assert_eq!(
            admit(&receiver, 7, &frame(3, b"p"), DEPTH),
            Admission::Judge,
            "a stream the receiver does not have is the judge's to refuse"
        );
    }

    #[test]
    fn a_reply_of_the_baseline_frame_is_a_duplicate_and_one_behind_it_is_stale() {
        let mut receiver = receiver();
        let live = frame(10, b"ten");
        assert_eq!(receiver.receive(0, &live, 0).unwrap().status, Status::First);
        assert_eq!(admit(&receiver, 0, &live, DEPTH), Admission::Duplicate);
        assert_eq!(
            admit(&receiver, 0, &frame(10, b"TEN"), DEPTH),
            Admission::Judge,
            "the same counter with another CRC is the judge's repetition"
        );
        for behind in 1..DEPTH as u64 {
            assert_eq!(
                admit(&receiver, 0, &frame(10 - behind, b"old"), DEPTH),
                Admission::Stale,
                "{behind} behind"
            );
        }
        assert_eq!(
            admit(&receiver, 0, &frame(10 - DEPTH as u64, b"old"), DEPTH),
            Admission::Judge,
            "a whole ring behind: the publisher started again"
        );
        assert_eq!(
            admit(&receiver, 0, &frame(11, b"new"), DEPTH),
            Admission::Judge
        );
        assert_eq!(
            admit(&receiver, 1, &live, DEPTH),
            Admission::Judge,
            "the other stream has no baseline"
        );
        let mut corrupt = live.clone();
        corrupt[0] ^= 0x01;
        assert_eq!(
            admit(&receiver, 0, &corrupt, DEPTH),
            Admission::Judge,
            "a frame that is not intact is the judge's to report"
        );
        assert_eq!(
            receiver.standing(0, &live).map(|s| s.baseline),
            Some(10),
            "nothing moved"
        );
    }

    /// The baseline frame is the one that moved the baseline: a repetition with another CRC
    /// leaves the duplicate test on the first.
    #[test]
    fn a_repetition_does_not_become_the_baseline_frame() {
        let mut receiver = receiver();
        let first = frame(5, b"a");
        let again = frame(5, b"b");
        receiver.receive(0, &first, 0).unwrap();
        assert_eq!(
            receiver.receive(0, &again, 1).unwrap().status,
            Status::Repeated
        );
        assert_eq!(admit(&receiver, 0, &first, DEPTH), Admission::Duplicate);
        assert_eq!(admit(&receiver, 0, &again, DEPTH), Admission::Judge);
        let next = frame(6, b"c");
        receiver.receive(0, &next, 2).unwrap();
        assert_eq!(admit(&receiver, 0, &next, DEPTH), Admission::Duplicate);
        assert_eq!(admit(&receiver, 0, &first, DEPTH), Admission::Stale);
    }
}
